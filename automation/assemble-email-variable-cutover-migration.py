#!/usr/bin/env python3
"""Freeze a one-way rewrite of active template sources and reject the old format."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
renames = json.loads((ROOT / 'automation/email-template-cutover/renames.json').read_text())
assert all(re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', name) for pair in renames.items() for name in pair)
expression = 'p_text'
for old, new in renames.items():
    expression = "regexp_replace(" + expression + ", '\\{\\{[[:space:]]*" + old + "[[:space:]]*\\}\\}', '{{" + new + "}}', 'g')"

content = '''-- Generated by automation/assemble-email-variable-cutover-migration.py.
-- Execute atomically with authoring paused and email preparation/sends drained.
-- Only active template sources change; encrypted mail/history/receipts stay immutable.
DO $$ DECLARE is_paused boolean; BEGIN
 SELECT paused INTO is_paused FROM public.email_capacity WHERE singleton FOR UPDATE;
 IF is_paused IS DISTINCT FROM true OR EXISTS(SELECT 1 FROM public.email_messages
   WHERE workflow_state IN ('preparing','sending')) THEN
  RAISE EXCEPTION 'Pause and drain the canonical email queue before the variable cutover';
 END IF;
END $$;
LOCK TABLE public.email_templates,public.email_wrappers,public.occasion_setup_drafts IN ACCESS EXCLUSIVE MODE;
CREATE TEMP TABLE email_variable_cutover_counts(kind text,changed bigint) ON COMMIT DROP;
CREATE FUNCTION pg_temp.rename_email_template_variables(p_text text)
RETURNS text LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT ''' + expression + '''; $$;

WITH changed AS (
 UPDATE public.email_templates SET subject=pg_temp.rename_email_template_variables(subject),
   html=pg_temp.rename_email_template_variables(html)
 WHERE subject IS DISTINCT FROM pg_temp.rename_email_template_variables(subject)
    OR html IS DISTINCT FROM pg_temp.rename_email_template_variables(html) RETURNING id
) INSERT INTO email_variable_cutover_counts SELECT 'templates',count(*) FROM changed;
WITH changed AS (
 UPDATE public.email_wrappers SET html=pg_temp.rename_email_template_variables(html)
 WHERE html IS DISTINCT FROM pg_temp.rename_email_template_variables(html) RETURNING id
) INSERT INTO email_variable_cutover_counts SELECT 'wrappers',count(*) FROM changed;

CREATE FUNCTION pg_temp.rename_email_template_overrides(p_overrides jsonb)
RETURNS jsonb LANGUAGE sql IMMUTABLE STRICT AS $$
 SELECT CASE WHEN jsonb_typeof(p_overrides)='object' THEN coalesce((
  SELECT jsonb_object_agg(item.key,CASE WHEN jsonb_typeof(item.value)='object' THEN item.value
    || CASE WHEN jsonb_typeof(item.value->'subject')='string' THEN
      jsonb_build_object('subject',pg_temp.rename_email_template_variables(item.value->>'subject')) ELSE '{}'::jsonb END
    || CASE WHEN jsonb_typeof(item.value->'html')='string' THEN
      jsonb_build_object('html',pg_temp.rename_email_template_variables(item.value->>'html')) ELSE '{}'::jsonb END
    ELSE item.value END) FROM jsonb_each(p_overrides) item),'{}'::jsonb)
  ELSE p_overrides END;
$$;
WITH changed AS (
 UPDATE public.occasion_setup_drafts SET data=jsonb_set(data,'{emailTemplateOverrides}',
   pg_temp.rename_email_template_overrides(data->'emailTemplateOverrides')),
   revision=revision+1,updated_at=clock_timestamp()
 WHERE data->'emailTemplateOverrides' IS DISTINCT FROM
   pg_temp.rename_email_template_overrides(data->'emailTemplateOverrides') RETURNING id
) INSERT INTO email_variable_cutover_counts SELECT 'drafts',count(*) FROM changed;
'''
for source in [
    'database/functions/others/email_variable_contract.sql',
    'database/functions/eshop_waitlist/email_templates.sql',
    'database/functions/sale_opening_notifications/email_templates.sql',
]:
    content += '\n-- Source: ' + source + '\n' + (ROOT / source).read_text() + '\n'
content += '''
ALTER TABLE public.email_templates DROP CONSTRAINT IF EXISTS email_templates_canonical_variables;
ALTER TABLE public.email_templates ADD CONSTRAINT email_templates_canonical_variables
 CHECK(public.email_template_variables_are_canonical(subject) AND public.email_template_variables_are_canonical(html)) NOT VALID;
ALTER TABLE public.email_templates VALIDATE CONSTRAINT email_templates_canonical_variables;
ALTER TABLE public.email_wrappers DROP CONSTRAINT IF EXISTS email_wrappers_canonical_variables;
ALTER TABLE public.email_wrappers ADD CONSTRAINT email_wrappers_canonical_variables
 CHECK(public.email_template_variables_are_canonical(html)) NOT VALID;
ALTER TABLE public.email_wrappers VALIDATE CONSTRAINT email_wrappers_canonical_variables;
ALTER TABLE public.occasion_setup_drafts DROP CONSTRAINT IF EXISTS occasion_setup_drafts_canonical_email_variables;
ALTER TABLE public.occasion_setup_drafts ADD CONSTRAINT occasion_setup_drafts_canonical_email_variables
 CHECK(public.email_template_overrides_are_canonical(data->'emailTemplateOverrides')) NOT VALID;
ALTER TABLE public.occasion_setup_drafts VALIDATE CONSTRAINT occasion_setup_drafts_canonical_email_variables;
DO $$ DECLARE r record; BEGIN
 FOR r IN SELECT * FROM email_variable_cutover_counts LOOP
  RAISE NOTICE 'Canonical email variables: % rows changed in %',r.changed,r.kind;
 END LOOP;
END $$;
DROP FUNCTION pg_temp.rename_email_template_overrides(jsonb);
DROP FUNCTION pg_temp.rename_email_template_variables(text);
DROP TABLE pg_temp.email_variable_cutover_counts;
'''
target = ROOT / 'supabase/migrations/20261109160000_canonical_email_variables.sql'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('Canonical email-variable cutover migration is stale')
else:
    target.write_text(content)
