#!/usr/bin/env python3
"""Freeze delegated inventory adapters from their canonical SQL source."""
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
source = 'database/functions/inventory/delegated_assignments.sql'
target = root / 'supabase/migrations/20261110110000_mcp_inventory_assignments.sql'
content = '-- Generated by automation/assemble-mcp-completion-migration.py.\n-- Source: ' + source + '\n' + (root / source).read_text()
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('MCP completion migration differs from canonical SQL')
else:
    target.write_text(content)
