#!/usr/bin/env python3
"""Build-time expansion of private pure SQL rules in one SQL projection.

The authored rules remain SQL. No client policy, ACL table, role dispatcher or
request cache is generated. Strings/comments are tokenized before substitution.
"""
import argparse,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'automation'))
from generate_canonical_source_contract import CREATE,statements
TOKEN=re.compile(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|--[^\n]*|/\*.*?\*/|[A-Za-z_]\w*|\s+|.",re.S)
def tokens(sql):
 return [(m[0],m.start(),m.end()) for m in TOKEN.finditer(sql) if not m[0].isspace() and not m[0].startswith(('--','/*'))]
def rules():
 result={}
 for filename in ['operation_rules.sql','email_operations.sql','bank_operations.sql']:
  text=(ROOT/'database/functions/user_permissions'/filename).read_text()
  for statement in statements(text):
   m=CREATE.search(statement)
   if not m or not re.match(r'\s*boolean\b',m[3],re.I) or not re.search(r'\bIMMUTABLE\b',m[3],re.I):continue
   if not re.search(r'LANGUAGE\s+sql\b',m[3],re.I) or re.search(r'SECURITY\s+DEFINER',m[3],re.I):raise ValueError('Only pure invoker SQL rules can be expanded')
   body=m[5].strip();expression=re.fullmatch(r'SELECT\s+(.*);',body,re.I|re.S)
   if not expression:raise ValueError('Expected exactly one SQL expression')
   if any(t[0].upper() in {'FROM','JOIN','EXECUTE','INSERT','UPDATE','DELETE'} for t in tokens(body)):raise ValueError('A rule cannot read or mutate stored data')
   parameters=[p.strip().split()[0] for p in m[2].split(',')]
   name=m[1].removeprefix('public.')
   if name in result:raise ValueError('Ambiguous rule overload: '+name)
   result[name]=(parameters,expression[1])
 return result
RULES=rules()
SOURCE=ROOT/'automation/authorization/context_capabilities.sql.in'
TARGET=ROOT/'database/functions/user_permissions/context_capabilities.sql'
def substitute(expression,bindings):
 out=[];last=0
 for value,start,end in tokens(expression):
  if value in bindings:
   out.extend([expression[last:start],'('+bindings[value]+')']);last=end
 out.append(expression[last:]);return ''.join(out)
def expand(sql,stack=()):
 ts=tokens(sql);out=[];last=0;i=0
 while i<len(ts)-3:
  if ts[i][0]=='public' and ts[i+1][0]=='.' and ts[i+2][0] in RULES and ts[i+3][0]=='(':
   name=ts[i+2][0]
   if name in stack:raise ValueError('Recursive rule '+name)
   depth=0;args=[];begin=ts[i+3][2];j=i+4
   while j<len(ts):
    value,start,end=ts[j]
    if value==')' and depth==0:
     args.append(sql[begin:start].strip());break
    if value==',' and depth==0:args.append(sql[begin:start].strip());begin=end
    elif value=='(':depth+=1
    elif value==')':depth-=1
    j+=1
   else:raise ValueError('Unclosed rule call')
   parameters,body=RULES[name]
   if len(parameters)!=len(args):raise ValueError('Wrong rule argument count: '+name)
   bindings=dict(zip(parameters,[expand(a,stack) for a in args]))
   expression=expand(substitute(body,bindings),stack+(name,))
   out.extend([sql[last:ts[i][1]],'('+expression+')']);last=ts[j][2];i=j+1
  else:i+=1
 out.append(sql[last:]);return ''.join(out)
def render(source=None):
 if source is None:source=SOURCE.read_text()
 first=next(m for statement in statements(source) if (m:=CREATE.search(statement)) and m[1]=='public.get_context_capabilities_v1')
 # Replace only the private context constructor. Other RPCs retain their exact
 # declarations, grants and bodies, and domain row predicates remain inlineable.
 start=source.index(first[5],source.index('CREATE OR REPLACE FUNCTION public.get_context_capabilities_v1'))
 return source[:start]+expand(first[5])+source[start+len(first[5]):]
def generated():
 return '-- Generated by automation/generate_authorization_projection.py from authored SQL rules.\n'+render()
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 expected=generated()
 if args.check:
  if not TARGET.exists() or TARGET.read_text()!=expected:raise SystemExit('Authorization SQL projection is stale')
 else:TARGET.write_text(expected)
