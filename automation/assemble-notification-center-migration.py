#!/usr/bin/env python3
"""Generate the additive notification migration from its explicit canonical owners."""
from pathlib import Path
import argparse
root=Path(__file__).resolve().parents[1]
SOURCES=[
 'notification_center/schema.sql','notification_center/core.sql','notification_center/orders.sql',
 'notification_center/capacity.sql','notification_center/email.sql','notification_center/maintenance.sql','notification_center/bank.sql',
 'eshop/create_ticket_order.sql','eshop/finalize_ticket_order.sql','eshop_waitlist/commands.sql','eshop_waitlist/offers.sql','eshop_waitlist/fakturoid_recovery.sql',
 'eshop_orders/internal_storno_tickets_221.sql','eshop_orders/update_order_and_tickets_to_paid.sql','eshop_orders/update_order_and_tickets_to_sent.sql',
 'eshop_orders/recalculate_order_payment_status.sql','eshop_forms/update_form.sql','eshop/update_product.sql','eshop/update_blueprint.sql',
 'inventory/apply_allocations.sql','inventory/adjust_spot_capacity_for_pool.sql','eshop_stripe/ingest.sql','emails/email_queue.sql','seed/crons.sql',
]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
out=root/'supabase/migrations/20261023210000_organization_notification_center.sql'
text='-- Generated by automation/assemble-notification-center-migration.py. Activation defaults OFF.\n'
text+='BEGIN;\n'+''.join('\n-- SOURCE: '+source+'\n'+(root/'database/functions'/source).read_text()+'\n' for source in SOURCES)
text+='''
-- Register without guessing a live URL. The machine-proof target follows the existing queue owner.
DO $$ DECLARE worker text; BEGIN
 IF EXISTS(SELECT 1 FROM pg_extension WHERE extname='pg_cron') THEN
  PERFORM cron.schedule('festapp_canonical_notification_center_project','*/1 * * * *','SELECT public.maintain_notification_center(100)');
  SELECT worker_url INTO worker FROM public.email_capacity WHERE worker_url IS NOT NULL;
  IF worker IS NOT NULL THEN
   PERFORM cron.schedule('festapp_canonical_notification_center_health','*/5 * * * *',
    format($job$SELECT net.http_post(url:=%L,body:=jsonb_build_object('requestSecret',public.generate_request_secret(3600)),timeout_milliseconds:=240000)$job$,
      regexp_replace(worker,'/functions/v1/[^/]+$','/functions/v1/notification-center-maintain')));
  END IF;
 END IF;
END $$;
COMMIT;
'''
tables=root/'database/tables/tables.sql'
start='\n-- Organization notification center private projections.\n'
end='-- End organization notification center private projections.\n'
block=start+(root/'database/functions/notification_center/schema.sql').read_text()+(root/'database/functions/notification_center/maintenance.sql').read_text().split('CREATE OR REPLACE FUNCTION')[0]+end
current=tables.read_text()
if start in current:
 before,tail=current.split(start,1)
 if end not in tail: raise SystemExit('Notification schema marker is incomplete')
 canonical_tables=before+block+tail.split(end,1)[1]
else: canonical_tables=current+block
if args.check:
 if canonical_tables!=current: raise SystemExit('Notification table definitions differ from canonical schema')
 if not out.exists() or out.read_text()!=text: raise SystemExit('Notification migration differs from canonical sources')
 print('Notification migration matches canonical sources')
else:
 out.write_text(text)
 tables.write_text(canonical_tables)
 print(out.relative_to(root))
