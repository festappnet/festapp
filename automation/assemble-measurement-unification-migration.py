#!/usr/bin/env python3
"""Forward migration for the single structural runtime-support owner."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'supabase/migrations/20261110210000_measurement_runtime_support.sql'
SOURCES = ['form_measurement_support.sql', 'form_measurement_policy.sql',
           'unit_measurement_approval.sql']
text = '-- Generated by automation/assemble-measurement-unification-migration.py.\nBEGIN;\n'
for name in SOURCES:
    path = 'database/functions/eshop_forms/' + name
    text += '\n-- Source: ' + path + '\n' + (ROOT / path).read_text()
text += "\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not TARGET.exists() or TARGET.read_text() != text:
        raise SystemExit('Measurement support forward migration is stale')
else:
    TARGET.write_text(text)
