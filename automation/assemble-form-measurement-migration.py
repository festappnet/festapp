#!/usr/bin/env python3
"""Assemble the form measurement migration from its canonical SQL owners."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    'eshop_forms/form_measurement_limits.sql',
    'user_permissions/form_measurement.sql',
    'user_permissions/context_capabilities.sql',
    'eshop_forms/form_settings.sql',
    'eshop_forms/update_form.sql',
    'occasion_setup/sources.sql',
    'occasion_setup/finalize.sql',
    'eshop_forms/duplicate_form_to_occasion.sql',
    'others/duplicate_occasion.sql',
    'eshop_forms/form_datalayer.sql',
    'eshop_orders/create_ticket_order_client_sync_v1.sql',
]
TARGET = ROOT / 'supabase/migrations/20261106090000_form_measurement.sql'

def render():
    return '-- Generated by automation/assemble-form-measurement-migration.py.\n' + '\n'.join(
        f'\n-- Source: database/functions/{name}\n' + (ROOT / 'database/functions' / name).read_text().rstrip() + '\n'
        for name in SOURCES
    )

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit('Form measurement migration differs from canonical SQL')
    else:
        TARGET.write_text(expected)
