#!/usr/bin/env python3
"""Assemble the form measurement migration from its canonical SQL owners."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    'eshop_forms/form_measurement_limits.sql',
    'others/configuration_settings_contract.sql',
    'organization/update_organization_admin.sql',
    'eshop_forms/form_measurement_schema_cutover.sql',
    'eshop_forms/form_measurement_policy.sql',
    'others/get_app_config.sql',
    'others/get_public_occasions.sql',
    'others/get_unit_for_edit.sql',
    'user_permissions/form_measurement.sql',
    'eshop_forms/form_measurement_runtime.sql',
    'user_permissions/context_capabilities.sql',
    'eshop_forms/form_settings.sql',
    'eshop_forms/form_measurement_unit_cutover.sql',
    'eshop_forms/get_effective_form_data.sql',
    'eshop_forms/get_form_for_edit.sql',
    'eshop_forms/admin_form_reads.sql',
    'eshop_forms/update_form.sql',
    'occasion_setup/sources.sql',
    'occasion_setup/finalize.sql',
    'eshop_forms/duplicate_form_to_occasion.sql',
    'others/duplicate_occasion.sql',
    'eshop_forms/form_datalayer.sql',
    'eshop_orders/create_ticket_order_client_sync_v1.sql',
    'eshop_waitlist/commands.sql',
]
TARGET = ROOT / 'supabase/migrations/20261106100000_form_measurement_policy.sql'

def render():
    return '-- Generated by automation/assemble-form-measurement-migration.py.\n' + '\n'.join(
        f'\n-- Source: database/functions/{name}\n' + (ROOT / 'database/functions' / name).read_text().rstrip() + '\n'
        for name in SOURCES
    )

def schema_snapshot():
    policy = (ROOT / 'database/functions/eshop_forms/form_measurement_policy.sql').read_text()
    marker = '-- Form measurement protected schema:'
    schema = ROOT / 'database/tables/tables.sql'
    prefix = schema.read_text().split(marker)[0]
    return schema, prefix + marker + ' generated from eshop_forms/form_measurement_policy.sql.\n' + \
        policy.split('-- Shared redaction')[0] + policy[policy.index('CREATE TABLE IF NOT EXISTS analytics.conversion_facts'):]

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    schema, expected_schema = schema_snapshot()
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit('Form measurement migration differs from canonical SQL')
        if schema.read_text() != expected_schema:
            raise SystemExit('Measurement schema snapshot differs from canonical owner')
    else:
        TARGET.write_text(expected)
        schema.write_text(expected_schema)
