#!/usr/bin/env python3
"""Seal or verify one tenant web artifact in its existing version manifest."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'automation/ci'))
from resources import flutter_slot

MANIFEST = 'festapp-version.json'


def command(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':')).encode()


def tools():
    version = command('node', 'automation/flutter_version.mjs')
    flutter = ['flutter'] if shutil.which('flutter') else []
    with flutter_slot():
        if flutter:
            raw = command(*flutter, '--version', '--machine')
            info = json.loads(raw[raw.index('{'):])
            if info['frameworkVersion'] != version:
                flutter = []
        if not flutter:
            if shutil.which('fvm'):
                raw = command('fvm', 'spawn', version, '--version', '--machine')
            else:
                installed = Path(os.environ.get('FESTAPP_FLUTTER_INSTALL_DIR',
                                                Path.home()/f'.cache/festapp/flutter-{version}'))
                raw = command(str(installed/'bin/flutter'), '--version', '--machine')
            info = json.loads(raw[raw.index('{'):])
        if info['frameworkVersion'] != version:
            raise ValueError('Flutter does not match the configured build toolchain')
    return {'flutter': {key: info[key] for key in
                        ('frameworkVersion', 'frameworkRevision', 'engineRevision', 'dartSdkVersion')},
            'node': command('node', '--version'), 'pnpm': command('pnpm', '--version'),
            'deno': command('deno', '--version')}


def inputs(target):
    # Hash actual tracked/generated bytes, including modes, deletions and symlink
    # targets, not just HEAD. Generated tenant leaves are checked after apply_config.
    records = {}
    names = subprocess.check_output(['git', 'ls-files', '-z', '--cached', '--others',
                                     '--exclude-standard'], cwd=ROOT).split(b'\0')
    paths = {os.fsdecode(name) for name in names if name}
    for directory in ('web', 'web_client/public'):
        paths.update(str(p.relative_to(ROOT)) for p in (ROOT / directory).rglob('*')
                     if p.is_file() or p.is_symlink())
    for name in sorted(paths):
        path = ROOT / name
        if path.is_symlink():
            records[name] = ['symlink', os.readlink(path)]
        elif path.is_file():
            records[name] = [path.stat().st_mode & 0o777, sha256(path.read_bytes())]
        else:
            records[name] = ['deleted']
    overlay = json.loads((ROOT / 'automation/tenant-overlay.json').read_text())
    return {'mainSha': overlay['baseMainSha'], 'tenantSha': command('git', 'rev-parse', 'HEAD'),
            'tenantId': overlay['tenantId'], 'target': target,
            'configSha256': sha256((ROOT / 'automation/project.conf').read_bytes()),
            'sourceAndGeneratedSha256': sha256(canonical(records)), 'toolchain': tools(),
            'flags': {'flutter': ['--release', '--base-href', '/', '--no-web-resources-cdn', '--no-wasm-dry-run'],
                      'environment': {key: sha256(os.environ.get(key, '').encode()) for key in
                                      ('DART_DEFINES', 'FLUTTER_BUILD_MODE', 'FLUTTER_WEB_RENDERER',
                                       'FESTAPP_CANONICAL_CUTOVER_RELEASE')}}}


def outputs(directory):
    records = {}
    for path in sorted(directory.rglob('*')):
        if path.is_symlink():
            raise ValueError('Web artifact must not contain symlinks')
        if not path.is_file():
            continue
        name = str(path.relative_to(directory))
        content = path.read_bytes()
        if name == MANIFEST:
            manifest = json.loads(content)
            manifest.pop('buildReceipt', None)
            content = canonical(manifest)
        records[name] = sha256(content)
    if MANIFEST not in records or len(records) < 2:
        raise ValueError('Incomplete web artifact')
    return sha256(canonical(records))


def seal(directory, target, before):
    manifest_path = directory / MANIFEST
    manifest = json.loads(manifest_path.read_text())
    if 'buildReceipt' in manifest:
        raise ValueError('Artifact is already sealed; rebuild instead of relabelling')
    current = inputs(target)
    if current != before:
        raise ValueError('Source or toolchain changed during compilation; refusing to seal')
    manifest['buildReceipt'] = {'schemaVersion': 1, 'builtAtUnixSeconds': time.time(),
                                'inputs': current, 'outputsSha256': outputs(directory)}
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')


def verify(directory, target):
    manifest = json.loads((directory / MANIFEST).read_text())
    receipt = manifest['buildReceipt']
    if (receipt['schemaVersion'] != 1 or receipt['inputs'] != inputs(target) or
            receipt['outputsSha256'] != outputs(directory)):
        raise ValueError('Artifact receipt mismatch; perform a fresh canonical build')
    return receipt


def preserve(directory):
    manifest_path = directory / MANIFEST
    if not manifest_path.is_file():
        return
    manifest = json.loads(manifest_path.read_text())
    receipt = manifest.get('buildReceipt')
    if receipt is None:
        return  # Unsealed legacy/partial output is not an immutable artifact.
    actual = outputs(directory)
    if isinstance(receipt, dict) and receipt.get('schemaVersion') == 1 and receipt.get('outputsSha256') == actual:
        key = sha256(canonical(receipt))
    else:
        # Preservation is not reuse. Keep altered bytes for diagnosis while a
        # normal fresh build proceeds; verify() will still reject this artifact.
        key = 'unverified-' + sha256(canonical(receipt) + actual.encode())
    destination = directory.parent / 'web-artifacts' / key
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        raise ValueError('Immutable artifact destination already exists; refusing overwrite')
    directory.rename(destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['capture', 'seal', 'verify', 'preserve'])
    parser.add_argument('target', choices=['cloudflare', 'static'])
    args = parser.parse_args()
    directory = ROOT / 'build/web'
    snapshot = ROOT / 'build/web-build-inputs.json'
    if args.action == 'preserve':
        preserve(directory)
    elif args.action == 'capture':
        snapshot.parent.mkdir(parents=True, exist_ok=True)
        snapshot.write_text(json.dumps(inputs(args.target)) + '\n')
    elif args.action == 'seal':
        seal(directory, args.target, json.loads(snapshot.read_text()))
    else:
        verify(directory, args.target)
    print(f'Web build receipt: {args.action} passed ({args.target})')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        print(f'Web build receipt rejected: {error}', file=sys.stderr)
        sys.exit(1)
