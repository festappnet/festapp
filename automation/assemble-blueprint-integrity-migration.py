#!/usr/bin/env python3
"""Assemble the bounded forward blueprint integrity contract from B owners."""
from pathlib import Path
import argparse
import hashlib
import re
ROOT=Path(__file__).resolve().parents[1]
SOURCES=[
 'database/functions/eshop_waitlist/tickets.sql',
 'database/functions/eshop/create_ticket_order.sql',
 'database/functions/eshop_waitlist/accept_offer.sql',
 'database/functions/eshop_waitlist/commands.sql',
 'database/functions/eshop/finalize_ticket_order.sql',
 'database/functions/blueprint/validation.sql',
 'database/functions/blueprint/save.sql',
 'database/functions/blueprint/update_blueprint_client_sync_v1.sql',
 'database/functions/blueprint/swap_spot_tickets_client_sync_v1.sql',
 'database/functions/eshop/select_spot.sql',
 'database/functions/eshop/analyze_new_order_spots.sql',
 'database/functions/eshop/confirm_blueprint_order_change.sql',
 'database/functions/eshop/get_blueprint.sql',
 'database/functions/eshop/get_blueprint_for_edit.sql',
 'database/functions/eshop_orders/update_order_and_tickets_to_storno.sql',
 'database/functions/eshop_orders/update_order_and_tickets_to_storno_ws.sql',
 'database/functions/eshop_orders/storno_tickets_bulk.sql',
 'database/functions/eshop_orders/storno_order_client_sync_v1.sql',
 'database/functions/eshop_orders/storno_tickets_client_sync_v1.sql',
 'database/functions/others/update_occasion.sql',
 'database/functions/eshop/swap_spot_tickets.sql',
 'database/functions/blueprint/retire_staged_readers.sql',
]
TARGET=ROOT/'supabase/migrations/20261021010000_blueprint_reservation_integrity.sql'
text='-- Generated by automation/assemble-blueprint-integrity-migration.py.\n-- Forward-only: preserve B scopes, unified reminder owner and demo fence.\nBEGIN;\n'
text+='\n'.join(f'-- Source: {source}\n'+(ROOT/source).read_text() for source in SOURCES)+'\nCOMMIT;\n'
checks=[]
for source in SOURCES:
 for match in re.finditer(r'CREATE OR REPLACE FUNCTION (?:public\.)?(\w+)\([\s\S]*?AS\s+(\$\w*\$)([\s\S]*?)\2',(ROOT/source).read_text(),re.I):
  name,_,body=match.groups();digest=hashlib.md5(body.strip().encode()).hexdigest()
  checks.append(f" PERFORM public.assert_true(EXISTS(SELECT 1 FROM pg_proc WHERE pronamespace='public'::regnamespace AND proname='{name}' AND md5(btrim(prosrc,E' \\n\\r\\t'))='{digest}'),'blueprint SQL source parity: {name}');")
checks.append(" PERFORM public.assert_true(to_regprocedure('public.get_blueprint_legacy_rollout_internal(uuid,uuid,bigint)') IS NULL AND to_regprocedure('public.get_blueprint_for_edit_legacy_rollout_internal(text)') IS NULL,'obsolete staged rollout readers absent');")
parity='-- Generated by automation/assemble-blueprint-integrity-migration.py.\nDO $$ BEGIN\n'+'\n'.join(checks)+'\nEND $$;\n'
parity_target=ROOT/'database/tests/blueprint/integrity_source_parity_test.sql'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
 if TARGET.read_text()!=text or parity_target.read_text()!=parity: raise SystemExit('blueprint integrity generated SQL is stale')
else:
 TARGET.write_text(text)
 parity_target.write_text(parity)
print(f'blueprint integrity migration: {len(SOURCES)} canonical sources')
