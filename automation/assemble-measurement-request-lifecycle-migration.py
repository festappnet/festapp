#!/usr/bin/env python3
"""Assemble the current measurement request lifecycle owner."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'supabase/migrations/20261111160000_measurement_request_lifecycle.sql'
source = ROOT / 'database/functions/eshop_forms/unit_measurement_approval.sql'
text = "-- Generated by automation/assemble-measurement-request-lifecycle-migration.py.\nBEGIN;\n" + source.read_text() + "\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not TARGET.exists() or TARGET.read_text() != text:
        raise SystemExit('Measurement request lifecycle migration is stale')
else:
    TARGET.write_text(text)
