import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:image/image.dart' as image;

// This encoder supplies test data, not the behavior exercised by the browser.
// Keep the original JPEG dimensions and bytes without encoding them in Chrome.
void main(List<String> args) {
  if (args.isNotEmpty && (args.length != 1 || args.single != '--check')) {
    throw ArgumentError('Usage: generate_preview_image_fixture.dart [--check]');
  }
  final bytes = image.encodeJpg(image.Image(width: 3000, height: 2000));
  final encoded = base64Encode(bytes);
  final output = StringBuffer()
    ..writeln(
      '// Generated by automation/testing/generate_preview_image_fixture.dart.',
    )
    ..writeln(
      '// JPEG 3000x2000; ${bytes.length} bytes; SHA-256 ${sha256.convert(bytes)}.',
    )
    ..writeln('const largePreviewJpegBase64 =');
  for (var start = 0; start < encoded.length; start += 76) {
    final end = start + 76 < encoded.length ? start + 76 : encoded.length;
    output.writeln(
      "    '${encoded.substring(start, end)}'${end == encoded.length ? ';' : ''}",
    );
  }
  final file = File('test/components/html/large_preview_jpeg_fixture.dart');
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != output.toString()) {
      stderr.writeln(
        'Preview JPEG fixture is stale. Run: fvm dart run '
        'automation/testing/generate_preview_image_fixture.dart',
      );
      exitCode = 1;
    }
  } else {
    file.writeAsStringSync(output.toString());
  }
}
