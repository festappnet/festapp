#!/usr/bin/env python3
"""Prepare English demo lettering with the canonical bundled-font shaper."""
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
locale_source = (ROOT / 'database/fixtures/demo_occasions/locales.sql').read_text()
locale = re.search(r"\('en','((?:''|[^'])*)'::jsonb\)", locale_source)
TRANSLATIONS = json.loads(locale[1].replace("''", "'"))['blueprintLabels']

source = (ROOT / 'database/fixtures/demo_occasions/reference.sql').read_text()
reference = json.loads(re.search(r"VALUES \('(.*)'::jsonb\)", source)[1].replace("''", "'"))
old_ids, requests = [], []
for identity, resource in reference['resources']['textLayouts'].items():
    request = resource['descriptor']['request']
    if request['text'] in TRANSLATIONS:
        old_ids.append(identity)
        requests.append({**request, 'text': TRANSLATIONS[request['text']]})
assert len(requests) == 4
with tempfile.TemporaryDirectory(prefix='festapp-demo-en-') as directory:
    path = Path(directory)
    (path / 'proposals.json').write_text(json.dumps([{'requests': requests, 'numericFaces': []}]))
    subprocess.run(['deno', 'run', '--allow-read', '--allow-write', '--allow-env',
                    'automation/blueprint-cutover/prepare_text.ts', directory], cwd=ROOT, check=True)
    resources = json.loads((path / 'prepared-proposals.json').read_text())[0]['prepared']
assert all(reference['resources']['fontFamilies'][key] == value
           for key, value in resources['fontFamilies'].items())
quote = lambda value: "'" + value.replace("'", "''") + "'"
encoded = json.dumps(resources['textLayouts'], separators=(',', ':'))
mapping = json.dumps(TRANSLATIONS, ensure_ascii=False)
sql = """-- Generated by automation/prepare_english_demo_reference.py.
-- Geometry, seats, bundled fonts and numeric resources stay canonical.
UPDATE pg_temp.demo_reference_blueprint SET content =
 jsonb_set(jsonb_set(content, '{layout,nodes}', (SELECT jsonb_agg(
  CASE WHEN translations ? (node->>'text') THEN node || jsonb_build_object(
   'text', translations->>(node->>'text'), 'label', translations->>(node->>'text'))
  ELSE node END ORDER BY position)
 FROM jsonb_array_elements(content#>'{layout,nodes}') WITH ORDINALITY n(node,position),
 LATERAL (SELECT MAPPING::jsonb AS translations) t)),
 '{resources,textLayouts}', ((content#>'{resources,textLayouts}') - OLD_IDS::text[]) || PREPARED::jsonb);
""".replace('MAPPING', quote(mapping)).replace('OLD_IDS', quote('{' + ','.join(old_ids) + '}')).replace('PREPARED', quote(encoded))
(ROOT / 'database/fixtures/demo_occasions/reference.en.sql').write_text(sql)
print('Prepared four English labels; canonical geometry and numeric resources retained.')
