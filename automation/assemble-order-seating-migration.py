#!/usr/bin/env python3
"""Assemble the forward-only order seating presentation migration."""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    'eshop/order_seating.sql',
    'eshop/finalize_ticket_order.sql',
    'eshop/swap_spot_tickets.sql',
    'eshop/get_order_details_for_email.sql',
    'eshop_orders/get_orders.sql',
    'eshop_waitlist/order_overview.sql',
]
target = ROOT / 'supabase/migrations/20261021030000_order_seating.sql'
content = '-- Generated by automation/assemble-order-seating-migration.py.\nBEGIN;\n'
for source in SOURCES:
    content += f'\n-- Source: database/functions/{source}\n'
    content += (ROOT / 'database/functions' / source).read_text() + '\n'
content += 'COMMIT;\n'
# The existing catalog assertions track current canonical bodies, while older
# published migrations remain immutable.
parity_target = ROOT / 'database/tests/blueprint/integrity_source_parity_test.sql'
parity = parity_target.read_text()
for source in SOURCES:
    for match in re.finditer(r'CREATE OR REPLACE FUNCTION (?:public\.)?(\w+)\([\s\S]*?AS\s+(\$\w*\$)([\s\S]*?)\2', (ROOT / 'database/functions' / source).read_text(), re.I):
        name, _, body = match.groups()
        digest = hashlib.md5(body.strip().encode()).hexdigest()
        parity = re.sub(r"(proname='" + name + r"' AND md5\(btrim\(prosrc,.*?\)\)=')[a-f0-9]+(')",
                        lambda m: m[1] + digest + m[2], parity)

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != content or parity_target.read_text() != parity:
        raise SystemExit('Order seating migration differs from canonical sources')
    print('Order seating migration matches canonical sources')
else:
    target.write_text(content)
    parity_target.write_text(parity)
    print('Order seating migration assembled')
