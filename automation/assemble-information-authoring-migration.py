#!/usr/bin/env python3
"""Freeze the scoped information adapter from its canonical SQL owner."""
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
source = 'database/functions/authoring/information.sql'
target = root / 'supabase/migrations/20261120080000_song_authoring.sql'
content = '-- Generated by automation/assemble-information-authoring-migration.py.\n-- Source: ' + source + '\n' + (root / source).read_text()
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('Information authoring migration differs from canonical SQL')
else:
    target.write_text(content)
