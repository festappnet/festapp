#!/usr/bin/env python3
"""Assemble the forward measurement request boundary from canonical SQL."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
target = root / 'supabase/migrations/20261110190000_unit_measurement_approval_request.sql'
sql = '-- Generated by automation/assemble-measurement-approval-migration.py\nBEGIN;\n'
for source in ['eshop_forms/unit_measurement_approval.sql', 'units/delete_unit.sql']:
    sql += f'\n-- Source: database/functions/{source}\n' + (root / 'database/functions' / source).read_text()
queue = (root / 'database/functions/emails/email_queue.sql').read_text()
start = queue.index('CREATE OR REPLACE FUNCTION public.email_intent_valid(')
end = queue.index('END $$;', start) + len('END $$;')
sql += '\n-- Source: database/functions/emails/email_queue.sql (email_intent_valid only)\n' + queue[start:end] + '\nCOMMIT;\n'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != sql:
        raise SystemExit('Measurement approval migration is stale')
else:
    target.write_text(sql)
print('Measurement approval migration matches canonical SQL.')
