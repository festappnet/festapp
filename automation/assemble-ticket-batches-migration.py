#!/usr/bin/env python3
"""Assemble only the new ticket-batches forward migration from its explicit sources."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'automation/ticket-batches-sources.json'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    target = ROOT / manifest['migration']
    if target.name != '20261023200000_ticket_batches.sql' or target.is_symlink():
        raise SystemExit('Refusing an unexpected migration target')
    sources = manifest['sources']
    if len(sources) != len(set(sources)):
        raise SystemExit('Duplicate ticket-batch SQL source')
    content = '-- Generated by automation/assemble-ticket-batches-migration.py.\nBEGIN;\n'
    for source in sources:
        path = ROOT / source
        if not path.resolve().is_relative_to((ROOT / 'database/functions').resolve()):
            raise SystemExit('Source outside canonical SQL')
        body = path.read_text().rstrip()
        # The notification-center release owns these later, independently staged
        # hooks. Keep shared authored files intact and activate them only there.
        hooks = manifest.get('deferredHooks')
        if hooks:
            if hooks['prefix'] != 'notification_center_' or hooks['ownerMigration'] <= manifest['migration']:
                raise SystemExit('Invalid deferred hook owner')
            body = re.sub(r'PERFORM public\.notification_center_[a-z0-9_]+\([^;]*\);',
                          'NULL; -- Notification hook is activated by the later notification-center release.', body)
        content += f'\n-- Source: {source}\n{body}\n' 
    content += '\nCOMMIT;\n'
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('Ticket-batches migration differs from sources')
    else:
        target.write_text(content)

if __name__ == '__main__':
    main()
