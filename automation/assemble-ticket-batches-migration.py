#!/usr/bin/env python3
"""Assemble the one new batch feature migration; installed history is immutable."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((ROOT/'automation/ticket-batches-sources.json').read_text())
    target = ROOT/manifest['migration']
    if target.name != '20261024020000_pregenerated_ticket_batches.sql' or target.is_symlink():
        raise SystemExit('Refusing another migration target')
    sources = manifest['sources']
    if len(sources) != len(set(sources)): raise SystemExit('Duplicate source')
    sql = '-- Generated by automation/assemble-ticket-batches-migration.py.\nBEGIN;\n'
    for source in sources:
        path = ROOT/source
        if path.is_symlink() or not path.resolve().is_relative_to((ROOT/'database/functions').resolve()):
            raise SystemExit('Source outside canonical SQL')
        sql += f'\n-- Source: {source}\n{path.read_text().rstrip()}\n'
    sql += '\nCOMMIT;\n'
    if args.check:
        if not target.exists() or target.read_text() != sql: raise SystemExit('Migration differs from canonical sources')
    else: target.write_text(sql)
if __name__ == '__main__': main()
