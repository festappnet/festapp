#!/usr/bin/env python3
"""Build the forward notification fix without rewriting installed migrations."""
import migration_inputs
from pathlib import Path

root = Path(__file__).resolve().parent.parent
validator = migration_inputs.read_text(root / 'database/functions/emails/email_queue.sql')
start = validator.index('CREATE OR REPLACE FUNCTION public.email_intent_valid(')
end = validator.index('END $$;', start) + len('END $$;')
text = '-- Generated by automation/assemble-organization-verification-notifications.py\nBEGIN;\n'
for name in ['organization_verification/notifications.sql', 'organization_verification/profile_commands.sql', 'units/delete_unit.sql']:
    text += f'\n-- Source: database/functions/{name}\n' + migration_inputs.read_text(root / 'database/functions' / name)
text += '\n-- Source: database/functions/emails/email_queue.sql (email_intent_valid only)\n' + validator[start:end] + '\nCOMMIT;\n'
migration_inputs.write_text(root / 'supabase/migrations/20261019010000_unit_verification_notifications.sql', text)
