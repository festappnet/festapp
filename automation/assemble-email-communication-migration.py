#!/usr/bin/env python3
"""Assemble the forward communication contract without changing applied history."""
import migration_inputs
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    'database/functions/others/communication_tone.sql',
    'database/functions/eshop_forms/get_effective_form_data.sql',
    'database/functions/eshop_waitlist/email_copy.sql',
    'database/functions/occasion_setup/communication.sql',
    'database/functions/occasion_setup/email_preview.sql',
    'database/seeds/order_symbol_email_defaults.sql',
]
content = '-- Generated by automation/assemble-email-communication-migration.py.\n'
content += '-- Scoped custom templates and previously prepared messages are preserved.\n'
for source in SOURCES:
    content += '\n-- Source: ' + source + '\n' + migration_inputs.read_text(ROOT / source) + '\n'
content = content.rstrip() + '\n'
target = ROOT / 'supabase/migrations/20261109140000_email_communication.sql'
if '--check' not in sys.argv:
 raise SystemExit('Installed email communication migration is immutable; author a new forward migration')
import hashlib
from generate_canonical_source_contract import render
if target.is_symlink() or hashlib.sha256(migration_inputs.read_bytes(target)).hexdigest()!='a1e0d901199a475c31bd120de486dcb2f0277fbfea3f99aab8c387dd46065f85':
 raise SystemExit('Installed email communication migration bytes changed')
render(ROOT,additional_sources=[source.removeprefix('database/functions/') for source in SOURCES if source.startswith('database/functions/')])
print('Immutable email communication history and effective owners match')
