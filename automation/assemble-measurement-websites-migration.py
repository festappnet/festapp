#!/usr/bin/env python3
"""Assemble the forward organizer website proposal migration."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'supabase/migrations/20261111140000_measurement_websites.sql'
SOURCES = ['others/configuration_settings_contract.sql', 'eshop_forms/unit_measurement_approval.sql', 'emails/email_queue.sql']
text = '-- Generated by automation/assemble-measurement-websites-migration.py.\nBEGIN;\n'
for source in SOURCES:
    text += '\n-- Source: database/functions/' + source + '\n' + (ROOT / 'database/functions' / source).read_text()
text += "\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not TARGET.exists() or TARGET.read_text() != text:
        raise SystemExit('Measurement websites migration is stale')
else:
    TARGET.write_text(text)
