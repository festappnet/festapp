#!/usr/bin/env python3
"""Assemble the scoped blueprint order rejection correction."""
import migration_inputs
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'supabase/migrations/20261105220000_blueprint_order_recovery.sql'
SOURCES = ('blueprint/order_input.sql', 'blueprint/order_rejection.sql')


def render():
    return '-- Generated by automation/assemble-blueprint-recovery-migration.py.\n' + '\n'.join(
        '\n-- Source: database/functions/' + source + '\n' +
        migration_inputs.read_text(ROOT / 'database/functions' / source) for source in SOURCES
    ) + "\nNOTIFY pgrst, 'reload schema';\n"


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        if migration_inputs.read_text(TARGET) != render():
            raise SystemExit('Blueprint recovery migration differs from canonical sources')
    else:
        migration_inputs.write_text(TARGET, render())
