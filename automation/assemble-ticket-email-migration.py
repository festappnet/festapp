#!/usr/bin/env python3
"""Assemble only the changed ticket-delivery function contracts from canonical SQL."""
from pathlib import Path
import argparse
import re

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--output', required=True)
args = parser.parse_args()
output = Path(args.output)
if output.exists():
    raise SystemExit('Refusing to overwrite an existing migration')
functions = [
    ('others/ticket_layout.sql', 'ticket_delivery_mode', 1),
    ('others/ticket_layout.sql', 'merge_ticket_layout_features', 1),
    ('others/update_occasion.sql', 'update_occasion_internal_v1', 1),
    ('others/update_email_template.sql', 'update_email_template', 1),
    ('occasion_setup/drafts.sql', 'save_occasion_setup_draft', 1),
    ('occasion_setup/appearance.sql', 'normalize_occasion_setup_appearance_internal', 1),
    ('occasion_setup/email_templates.sql', 'validate_setup_email_templates_internal', 1),
    ('occasion_setup/email_preview.sql', 'get_occasion_setup_email_preview', 2),
]
parts = ['-- Generated by automation/assemble-ticket-email-migration.py. No data backfill.\nBEGIN;\n']
for path, name, count in functions:
    text = (root / 'database/functions' / path).read_text()
    matches = list(re.finditer(r'CREATE OR REPLACE FUNCTION public\.' + name + r'\s*\(', text))
    if len(matches) != count:
        raise SystemExit(f'Unexpected definition count for {name}: {len(matches)}')
    for match in matches:
        start = match.start()
        body = re.search(r'\bAS\s+(\$\w*\$)', text[start:], re.I)
        if body is None:
            raise SystemExit(f'Missing SQL body for {name}')
        tag = body.group(1)
        end_body = text.index(tag, start + body.end()) + len(tag)
        end = text.index(';', end_body) + 1
        parts.append(f'\n-- Source: database/functions/{path}\n' + text[start:end] + '\n')
parts.append('''
REVOKE ALL ON FUNCTION public.ticket_delivery_mode(jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.ticket_delivery_mode(jsonb) TO authenticated,service_role;
REVOKE ALL ON FUNCTION public.get_occasion_setup_email_preview(uuid,bigint,text,bigint,text),
 public.get_occasion_setup_email_preview(uuid,bigint) FROM PUBLIC,anon,service_role;
GRANT EXECUTE ON FUNCTION public.get_occasion_setup_email_preview(uuid,bigint,text,bigint,text),
 public.get_occasion_setup_email_preview(uuid,bigint) TO authenticated;
NOTIFY pgrst, 'reload schema';
COMMIT;
''')
output.write_text(''.join(parts))
print(f'Generated {output}')
