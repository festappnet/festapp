#!/usr/bin/env python3
"""Forward authorization SQL from final authored definitions, with parity checks.

No history is rewritten. Existing CREATE OR REPLACE definitions preserve grants;
new permission functions carry explicit grants in their canonical SQL sources.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'automation'))
from generate_canonical_source_contract import statements,CREATE,identity
BASE='6f6c5aa5108f0f67e150fb915d4c8bad9612c66c'
TARGET=ROOT/'supabase/migrations/20261021100000_canonical_authorization.sql'
ORDER=['user_permissions/operation_rules.sql','demo_occasions/access.sql','user_permissions/domain_operations.sql','user_permissions/technical_operations.sql','user_permissions/feature_operations.sql','user_permissions/get_can_manage_occasion_users.sql','user_permissions/email_operations.sql','user_permissions/bank_operations.sql','user_permissions/ticket_layout.sql',
       'user_permissions/get_is_editor_order_on_occasion.sql',
       'user_permissions/get_is_editor_order_view_on_occasion.sql',
       'user_permissions/context_capabilities.sql','synchronization/client_audit_reads.sql',
       'synchronization/private_client_sync.sql','events/get_event_editor_v1.sql','users/unit_access_deletion.sql','users/occasion_directory_reads.sql','others/remove_image_records.sql',
       'eshop_orders/update_ticket_products_client_sync_v1.sql','users/validate_occasion_user_csv_import_v1.sql','emails/legacy_template_delete.sql','users/occasion_enrolment_internal.sql','others/legacy_occasion_catalogs.sql','scanning/legacy_scan_ticket_v2.sql']
TAIL=['eshop_forms/form_creation_domain.sql','user_permissions/delegated_operations.sql','user_permissions/operation_policies.sql',
      'others/get_ticket_layout_write_contract_v1.sql','user_permissions/direct_write_contraction.sql','user_permissions/contraction.sql']

def render():
    from generate_authorization_projection import generated, TARGET as projection_target
    if projection_target.read_text()!=generated():raise ValueError('Regenerate the authorization SQL projection first')
    parts=['-- Generated by automation/assemble-authorization-migration.py.\nBEGIN;\n']
    parts.append('-- Source: database/indexes/canonical_authorization.sql\n'+(ROOT/'database/indexes/canonical_authorization.sql').read_text())
    files=subprocess.check_output(['git','diff',BASE,'--name-only','--','database/functions'],cwd=ROOT,text=True).splitlines()
    selected={}
    # Only changed CREATE FUNCTION statements, not schema/seed/drop statements.
    for name in files:
        source=name.removeprefix('database/functions/')
        if source in ORDER+TAIL or not (ROOT/name).exists():continue
        old=subprocess.check_output(['git','show',BASE+':'+name],cwd=ROOT,text=True)
        def bodies(sql):
            return {identity(m[1],m[2],True):stmt for stmt in statements(sql) if (m:=CREATE.search(stmt))}
        previous=bodies(old)
        for signature,stmt in bodies((ROOT/name).read_text()).items():
            if previous.get(signature)!=stmt:
                if signature in selected and selected[signature][1]!=stmt:
                    raise ValueError('Conflicting changed owners: '+signature)
                selected[signature]=(source,re.sub(r'CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION', 'CREATE OR REPLACE FUNCTION', stmt, count=1, flags=re.I))
    for source in ORDER:
        parts.append('-- Source: database/functions/'+source+'\n'+(ROOT/'database/functions'/source).read_text())
    for signature,(source,stmt) in sorted(selected.items()):
        parts.append('-- Source: database/functions/'+source+'\n'+stmt.strip()+'\n')
    for source in TAIL:
        parts.append('-- Source: database/functions/'+source+'\n'+(ROOT/'database/functions'/source).read_text())
    parts.append('COMMIT;\n')
    return '\n'.join(parts)
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();s=render()
    if a.check:
        if not TARGET.exists() or TARGET.read_text()!=s:raise SystemExit('Authorization migration is stale')
    else:TARGET.write_text(s)
