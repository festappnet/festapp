#!/usr/bin/env python3
"""Verify immutable admission history and its canonical forward corrections."""
from pathlib import Path
import re
import hashlib
root = Path(__file__).resolve().parents[1]
files = ['abuse/schema.sql', 'abuse/seeds.sql', 'abuse/policy.sql', 'abuse/budgets.sql', 'abuse/copy.sql',
         'others/create_occasion_domain_command_internal_v1.sql',
         'others/duplicate_occasion_client_sync_v1.sql', 'occasion_setup/drafts.sql',
         'occasion_setup/finalize.sql', 'units/create_unit_and_assign_manager.sql',
         'users/initialize_registration_unit_v1.sql', 'abuse/email.sql', 'abuse/scan.sql', 'abuse/orders.sql', 'notifications/dispatch_log_notification.sql', 'seed/triggers.sql', 'abuse/push.sql', 'notifications/publication.sql', 'cleaning/report_cleaning_issue.sql', 'eshop_orders/storno_order_client_sync_v1.sql', 'eshop_orders/storno_tickets_client_sync_v1.sql', 'eshop_orders/delete_order_client_sync_v1.sql', 'abuse/legacy_order_facades.sql', 'users/reception_qr_login.sql', 'abuse/reception.sql', 'eshop_orders/scan_ticket.sql', 'eshop_orders/get_occasion_by_scan_code.sql', 'eshop_orders/get_all_tickets_for_scan.sql', 'eshop_orders/update_ticket_to_used.sql', 'eshop_orders/update_ticket_to_used_ws.sql', 'eshop_orders/update_ticket_to_unused_ws.sql', 'eshop_orders/reset_password_via_scan.sql', 'abuse/qr.sql', 'abuse/auth.sql', 'abuse/media.sql', 'abuse/documents.sql', 'eshop_bank_sync/bank_sync_manage.sql',
         'emails/email_queue.sql', 'users/reset_user_password.sql', 'emails/email_domain.sql', 'eshop_waitlist/tickets.sql', 'eshop/select_spot.sql', 'eshop/create_ticket_order.sql', 'synchronization/sync_source_via_http.sql', 'synchronization/setup_external_source.sql',
         'seed/seed_org_with_admin.sql', 'abuse/acl.sql', 'abuse/storage.sql', 'others/add_image_record.sql', 'abuse/health.sql', 'abuse/participants.sql', 'abuse/image_projects.sql', 'support/monitoring_health.sql']
# The installed admission migration is immutable. Later corrections supersede
# selected function bodies without rebuilding already applied history.
installed = root / 'supabase/migrations/20261016100000_abuse_admission.sql'
historical = installed.read_text()
if hashlib.sha256(installed.read_bytes()).hexdigest() != '5ba74531a242669dd0a0b846af9648a6e63505a1b16494ec0b24b564d9a59f22':
    raise SystemExit('Installed abuse migration was changed')
# Index the applied forward definitions in migration order. Verify changed
# canonical functions against their actual forward migrations without rebuilding
# or weakening the immutable installed migration.
pattern = r'CREATE OR REPLACE FUNCTION (?:public\.)?(\w+)\([^;]*?\bAS\s+(\$\w*\$)[\s\S]*?\2(?:\s+LANGUAGE\s+"?\w+"?)?\s*;'
forward_sql = '\n'.join(p.read_text() for p in sorted((root / 'supabase/migrations').glob('*.sql')) if p.name > installed.name)
def normalized(value):
    return '\n'.join(line.rstrip() for line in value.splitlines()).strip()

forward_definitions = {m.group(1): normalized(m.group(0)) for m in re.finditer(pattern, forward_sql, re.I)}

def canonical_source(name):
    current_name = 'abuse/image_records.sql' if name == 'abuse/storage.sql' else name
    source = (root / 'database/functions' / current_name).read_text()
    marker = '-- Source: database/functions/' + name + '\n'
    original = historical.split(marker, 1)[1].split('\n-- Source:', 1)[0].split('\nUPDATE eshop.spots SET secret_expiration_time=', 1)[0].rstrip()
    if normalized(source) == normalized(original):
        return original + '\n'
    applied = {m.group(1): normalized(m.group(0)) for m in re.finditer(pattern, original, re.I)}
    applied.update(forward_definitions)
    matches = list(re.finditer(pattern, source, re.I))
    if not matches:
        raise SystemExit('Canonical non-function source drift: ' + name)
    for match in matches:
        if applied.get(match.group(1)) != normalized(match.group(0)):
            raise SystemExit('Missing forward migration for ' + match.group(1))
    return original + '\n'
text = '-- Generated by automation/assemble-abuse-migration.py. Proposed policy v1.\n'
for name in files:
    text += '\n-- Source: database/functions/' + name + '\n' + canonical_source(name) + '\n'
text += "\nUPDATE eshop.spots SET secret_expiration_time=least(coalesce(secret_expiration_time,'infinity'::timestamptz),now()+make_interval(secs=>(SELECT base_limit::integer FROM public.abuse_policy_rules WHERE rule_key='hold.duration.seconds'))) WHERE secret IS NOT NULL AND order_product_ticket IS NULL;\nREVOKE INSERT,UPDATE,DELETE ON public.organizations FROM anon,authenticated;\n"
text += "\n-- Preserve the reserved class of already accepted pending obligations, without admission/recharge.\nUPDATE public.email_messages m SET admission_class=public.email_admission_class_v1(m),priority=CASE WHEN public.email_admission_class_v1(m)='commitment' THEN 5 ELSE m.priority END WHERE m.workflow_state IN ('pending','blocked','preparing','sending','retry_wait','unknown');\n"
text = '\n'.join(line.rstrip() for line in text.splitlines()) + '\n'
output = root / 'supabase/migrations/20261016100000_abuse_admission.sql'
# Section-ending blank lines have varied in source files; the installed bytes
# remain protected by the exact SHA above and function bodies are checked above.
if [part.rstrip() for part in output.read_text().split('\n-- Source:')] != [part.rstrip() for part in text.split('\n-- Source:')]:
    raise SystemExit('Abuse source drift: add a canonical forward correction; do not rewrite installed history')
