import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const translations = new URL('../assets/translations/', import.meta.url);
const keys = ['table', 'group', 'couch', 'row', 'standingPlace', 'seat'];
const labels = Object.fromEntries(
  readdirSync(translations).filter(name => name.endsWith('.json')).sort().map(name => {
    const overview = JSON.parse(readFileSync(new URL(name, translations), 'utf8')).OrderOverview;
    const entries = keys.map(key => {
      if (!overview[key]?.trim()) throw new Error(`Missing ${key} seating label in ${name}`);
      return [key, overview[key]];
    });
    return [name.slice(0, -5), Object.fromEntries(entries)];
  }),
);
const wallet = Object.fromEntries(keys.map(key => [key, `${labels.cs[key]} / ${labels.en[key]}`]));
const serialized = value => JSON.stringify(value, null, 2);
const check = process.argv.includes('--check');
function write(file, content) {
  if (check) {
    if (readFileSync(file, 'utf8') !== content) throw new Error(`Regenerate ${file.pathname}`);
  } else {
    writeFileSync(file, content);
  }
}

// Project the authored translations into the backend and native preview.
function replaceLabels(file, contents) {
  const source = readFileSync(file, 'utf8');
  const block = /\/\/ BEGIN GENERATED SEATING LABELS\n[\s\S]*?\/\/ END GENERATED SEATING LABELS/;
  if (!block.test(source)) throw new Error(`Missing label markers in ${file.pathname}`);
  write(file, source.replace(block, () =>
    `// BEGIN GENERATED SEATING LABELS\n${contents}\n// END GENERATED SEATING LABELS`
  ));
}

const labelType = `type SeatingLabels = Record<${keys.map(JSON.stringify).join(" | ")}, string>;`;
replaceLabels(new URL('../supabase/functions/_shared/ticketRenderData.ts', import.meta.url),
  `${labelType}\nconst seatText: Record<string, SeatingLabels> = ${serialized(labels)};\n\n` +
  'export function seatingLabels(locale: string) {\n' +
  '  return Object.hasOwn(seatText, locale) ? seatText[locale] : seatText.en;\n}\n\n' +
  `export const walletSeatingLabels = ${serialized(wallet)};`
);
const sql = new URL('../database/functions/eshop/seating_labels.sql', import.meta.url);
const sqlSource = readFileSync(sql, 'utf8');
const sqlBlock = /  -- BEGIN GENERATED SEATING LABELS\n[\s\S]*?  -- END GENERATED SEATING LABELS/;
if (!sqlBlock.test(sqlSource)) throw new Error('Missing SQL seating label markers');
write(sql, sqlSource.replace(sqlBlock, () =>
  '  -- BEGIN GENERATED SEATING LABELS\n  catalog:=$labels$' +
  JSON.stringify(labels) + '$labels$::jsonb;\n  -- END GENERATED SEATING LABELS'
));
write(new URL('../packages/festapp_core/lib/wallet_seating_labels.dart', import.meta.url),
  '// Generated by automation/generate_seating_labels.mjs from OrderOverview translations.\n' +
  `const walletSeatGroupLabel = ${JSON.stringify(wallet.table)};\n` +
  `const walletSeatLabel = ${JSON.stringify(wallet.seat)};\n`
);
