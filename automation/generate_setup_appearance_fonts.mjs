#!/usr/bin/env node
// The selection owns UI choices; the immutable catalog owns face identity/bytes.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const selection = JSON.parse(fs.readFileSync(root + 'automation/tickets/setup-appearance-fonts.json'));
const catalog = JSON.parse(fs.readFileSync(root + 'supabase/functions/_shared/ticket-assets/font-catalog.json'));
const entries = Object.entries(selection);
for (const [family, id] of entries) {
  if (!catalog.fonts.some(face => face.id === id && (face.family === family || face.family === `${family} (legacy)`))) {
    throw new Error(`Unknown immutable face for ${family}: ${id}`);
  }
}
const quote = s => `'${s.replaceAll("'", "''")}'`;
const outputs = {
  'lib/components/occasion/setup/occasion_setup_font_ids.dart':
    '// Generated by automation/generate_setup_appearance_fonts.mjs.\n' +
    'const occasionSetupFontIds = <String, String>{\n' +
    entries.map(([family, id]) => `  '${family}':\n      '${id}',\n`).join('') + '};\n',
  'database/functions/occasion_setup/appearance_fonts.sql':
    '-- Generated by automation/generate_setup_appearance_fonts.mjs.\n' +
    'CREATE OR REPLACE FUNCTION public.occasion_setup_font_id_internal(p_family text)\n' +
    'RETURNS text LANGUAGE sql IMMUTABLE SET search_path=public,extensions AS $$\n' +
    ' SELECT CASE p_family\n' + entries.map(([family, id]) => `  WHEN ${quote(family)} THEN ${quote(id)}\n`).join('') +
    ' END\n$$;\nREVOKE ALL ON FUNCTION public.occasion_setup_font_id_internal(text) FROM PUBLIC,anon,authenticated,service_role;\n',
};
for (const [path, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(root + path, 'utf8') !== content) throw new Error(`Generated drift: ${path}`);
  } else fs.writeFileSync(root + path, content);
}
