#!/usr/bin/env python3
"""Project semantic consent scope without changing technical runtime leases."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'supabase/migrations/20261111120000_form_consent_scope.sql'
SOURCE = 'database/functions/eshop_forms/form_measurement_policy.sql'
text = '-- Generated by automation/assemble-consent-scope-migration.py.\nBEGIN;\n\n-- Source: ' + SOURCE + '\n' + (ROOT / SOURCE).read_text() + "\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not TARGET.exists() or TARGET.read_text() != text:
        raise SystemExit('Consent scope migration is stale')
else:
    TARGET.write_text(text)
