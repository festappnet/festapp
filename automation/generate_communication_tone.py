#!/usr/bin/env python3
"""Generate the same communication-tone contract for SQL, Dart and TypeScript."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
contract = json.loads((ROOT / 'packages/festapp_contracts/communication-tone.json').read_text())
values = contract['values']
default = contract['default']
inherit = contract['inherit']
assert default in values and inherit not in values and len(set(values)) == len(values)
assert all(value.isalpha() for value in values + [inherit])
banner = 'Generated by automation/generate_communication_tone.py; edit packages/festapp_contracts/communication-tone.json.'
quoted = ', '.join(repr(value) for value in values)
outputs = {
    'supabase/functions/_shared/communicationTone.ts': f'''// {banner}
export const communicationTones = [{quoted}] as const;
export type Tone = typeof communicationTones[number];
export const inheritedCommunicationTone = '{inherit}';
export function parseCommunicationTone(value: unknown): Tone | undefined {{
  return communicationTones.find((tone) => tone === value);
}}
/** Explicit setting, inherited organizer setting, then the platform default. */
export function resolveCommunicationTone(value: unknown, inherited?: unknown): Tone {{
  return parseCommunicationTone(value) ?? parseCommunicationTone(inherited) ?? '{default}';
}}
''',
    'packages/festapp_core/lib/communication_tone.dart': f'''// {banner}
abstract final class CommunicationTone {{
  static const values = <String>{{{quoted}}};
  static const defaultValue = '{default}';
  static const inherit = '{inherit}';

  static String? parse(Object? value) =>
      values.contains(value) ? value as String : null;

  /// Explicit setting, inherited organizer setting, then the platform default.
  static String resolve(Object? value, [Object? inherited]) =>
      parse(value) ?? parse(inherited) ?? defaultValue;
}}
''',
    'database/functions/others/communication_tone.sql': f'''-- {banner}
CREATE OR REPLACE FUNCTION public.parse_communication_tone(p_value text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path=public,extensions AS $$
 SELECT CASE WHEN p_value IN ({quoted}) THEN p_value END;
$$;
CREATE OR REPLACE FUNCTION public.resolve_communication_tone(p_value text,p_inherited text DEFAULT NULL)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path=public,extensions AS $$
 SELECT coalesce(public.parse_communication_tone(p_value),public.parse_communication_tone(p_inherited),'{default}');
$$;
REVOKE ALL ON FUNCTION public.parse_communication_tone(text),public.resolve_communication_tone(text,text)
 FROM PUBLIC,anon,authenticated,service_role;
GRANT EXECUTE ON FUNCTION public.parse_communication_tone(text),public.resolve_communication_tone(text,text)
 TO service_role;
''',
}
cases = (ROOT / 'packages/festapp_contracts/communication-tone-cases.json').read_text().strip()
outputs['database/tests/eshop_forms/communication_tone_test.sql'] = f'''-- {banner}
BEGIN;
DO $$
DECLARE c jsonb;
BEGIN
 FOR c IN SELECT value FROM jsonb_array_elements($cases${cases}$cases$::jsonb) LOOP
  ASSERT public.resolve_communication_tone(c->>'value',c->>'inherited') = c->>'expected',
    'Communication tone must follow the shared contract';
  ASSERT public.effective_form_metadata_internal(
    jsonb_build_object('communication_tone',c->'value'),
    jsonb_build_object('communication_tone',c->'inherited'))->>'communication_tone' = c->>'expected',
    'Form metadata must use the same inheritance as previews';
 END LOOP;
 ASSERT NOT has_function_privilege('authenticated','public.resolve_communication_tone(text,text)','EXECUTE');
END $$;
ROLLBACK;
'''
for name, content in outputs.items():
    path = ROOT / name
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit('Communication-tone contract is stale: ' + name)
    else:
        path.write_text(content)
