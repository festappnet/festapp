#!/usr/bin/env python3
"""Seal the email authoring owners into one additive forward migration."""
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
sources = ['others/email_template_commands.sql', 'others/get_all_email_templates.sql',
           'others/update_email_template.sql', 'others/delete_entity_email_template.sql',
           'units/begin_unit_client_mutation_v1.sql','others/update_entity_email_banner.sql','others/get_entity_email_templates.sql','occasion_setup/email_templates.sql']
content = '-- Generated by automation/assemble-email-template-migration.py.\n' + '\n\n'.join(
    '-- Source: database/functions/' + p + '\n' + (root / 'database/functions' / p).read_text()
    for p in sources)
target = root / 'supabase/migrations/20261026170000_email_template_commands.sql'
if '--check' in sys.argv:
    if target.read_text() != content: raise SystemExit('Email template migration differs from canonical sources')
else: target.write_text(content)
