#!/usr/bin/env python3
"""Build the filesystem-free Fontkit module used by isolated Edge workers."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
entry = root / 'automation/tickets/edge-fontkit.ts'
lock = root / 'supabase/functions/deno.lock'
target = root / 'supabase/functions/_shared/vendor/fontkit/fontkit.mjs'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

with tempfile.TemporaryDirectory(prefix='festapp-edge-fontkit-') as temporary:
    output = Path(temporary) / 'fontkit.mjs'
    subprocess.run([
        'deno', 'bundle', '--platform', 'browser', '--conditions', 'browser',
        '--minify', '--frozen', f'--lock={lock}', str(entry),
        '--output', str(output),
    ], cwd=root, check=True)
    bundle = b'// Generated by automation/tickets/build-edge-fontkit.py.\n' + output.read_bytes()
    if args.check:
        if target.read_bytes() != bundle:
            raise SystemExit('The Edge Fontkit module differs from its locked browser build')
    else:
        target.write_bytes(bundle)

# Retain upstream notices for the exact locked dependency tree.
graph = json.loads(subprocess.check_output(
    ['deno', 'info', '--json', f'--lock={lock}', str(entry)], cwd=root,
))
packages = graph['npmPackages']
pending = [module['npmPackage'] for module in graph['modules'] if module['kind'] == 'npm']
selected = set()
while pending:
    name = pending.pop()
    if name not in selected:
        selected.add(name)
        pending.extend(packages[name]['dependencies'])
notices = ['Fontkit browser build. Upstream license notices follow.']
for name in sorted(selected):
    folder = Path(packages[name]['localPath'])
    licenses = sorted(path for path in folder.iterdir()
                      if path.is_file() and path.name.lower().startswith(('license', 'licence', 'copying', 'notice')))
    notices.append(f'===== {name} =====')
    if licenses:
        notices.extend(path.read_text(errors='replace').strip() for path in licenses)
    else:
        notices.append('License: ' + json.loads((folder / 'package.json').read_text())['license'])
notice = '\n\n'.join(notices) + '\n'
notice_path = target.with_name('LICENSES.txt')
if args.check:
    if notice_path.read_text() != notice:
        raise SystemExit('The Edge Fontkit license notices differ from the locked dependency tree')
else:
    notice_path.write_text(notice)
