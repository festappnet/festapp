#!/usr/bin/env python3
"""Generate capability identifiers from the SQL projection, never client rules."""
import argparse
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'database/functions/user_permissions/context_capabilities.sql'

def render():
    keys=list(dict.fromkeys(re.findall(r"^\s*'([a-z_]+\.[a-z_.]+)',",SOURCE.read_text(),re.M)))
    assert keys and len(keys)==len(set(keys))
    def name(key):
        words=re.split('[_.]',key)
        return words[0]+''.join(w.title() for w in words[1:])
    header='// Generated by automation/generate_authorization_capabilities.py.\n'
    return {
      ROOT/'lib/data_services/authorization_capabilities.dart':header+'abstract final class AuthorizationCapabilities {\n'+''.join(f"  static const {name(k)} = '{k}';\n" for k in keys)+'}\n',
      ROOT/'web_client/src/services/authorization_capabilities.js':header+'export const AuthorizationCapabilities = Object.freeze({\n'+''.join(f"    {name(k)}: '{k}',\n" for k in keys)+'});\n',
      ROOT/'supabase/functions/_shared/authorizationCapabilities.ts':header+'export const AuthorizationCapabilities = {\n'+''.join(f"    {name(k)}: '{k}',\n" for k in keys)+'} as const;\n',
    }
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,text in render().items():
        if a.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale generated capabilities: {path}')
        else:path.write_text(text)
