#!/usr/bin/env python3
"""Narrow canonical function projection. --check compares the sealed migration."""
from pathlib import Path
import re, argparse
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--output',required=True);p.add_argument('--check',action='store_true');args=p.parse_args()
functions=[
 ('appearance_fonts.sql','occasion_setup_font_id_internal',1),
 ('appearance.sql','normalize_occasion_setup_appearance_internal',1),
 ('drafts.sql','initialize_occasion_setup_draft_defaults',1),
 ('drafts.sql','save_occasion_setup_draft',1),
 ('drafts.sql','delete_occasion_setup_draft',1),
 ('email_preview.sql','get_occasion_setup_email_preview',2),
 ('finalize.sql','finalize_occasion_setup_draft',1),
]
parts=['-- Generated by automation/assemble-wizard-reliability-migration.py. No backfill or font-byte changes.\nBEGIN;\n']
for path,name,count in functions:
 text=(root/'database/functions/occasion_setup'/path).read_text()
 matches=list(re.finditer(r'CREATE OR REPLACE FUNCTION public\.'+name+r'\s*\(',text))
 if len(matches)!=count:raise SystemExit('Unexpected function count: '+name)
 for match in matches:
  start=match.start();body=re.search(r'\bAS\s+(\$\w*\$)',text[start:],re.I);tag=body[1]
  end=text.index(';',text.index(tag,start+body.end())+len(tag))+1
  parts.append(f'\n-- Source: database/functions/occasion_setup/{path}\n'+text[start:end]+'\n')
parts.append('''
REVOKE ALL ON FUNCTION public.occasion_setup_font_id_internal(text),public.normalize_occasion_setup_appearance_internal(jsonb) FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON FUNCTION public.get_occasion_setup_email_preview(uuid,bigint), public.get_occasion_setup_email_preview(uuid,bigint,text,bigint,text) FROM PUBLIC,anon,service_role;
GRANT EXECUTE ON FUNCTION public.get_occasion_setup_email_preview(uuid,bigint), public.get_occasion_setup_email_preview(uuid,bigint,text,bigint,text) TO authenticated;
REVOKE ALL ON FUNCTION public.initialize_occasion_setup_draft_defaults(uuid,bigint),public.save_occasion_setup_draft(uuid,bigint,jsonb,integer),public.delete_occasion_setup_draft(uuid,bigint,bigint),public.finalize_occasion_setup_draft(uuid,bigint,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.initialize_occasion_setup_draft_defaults(uuid,bigint),public.save_occasion_setup_draft(uuid,bigint,jsonb,integer),public.delete_occasion_setup_draft(uuid,bigint,bigint),public.finalize_occasion_setup_draft(uuid,bigint,uuid) TO authenticated;
NOTIFY pgrst, 'reload schema';
COMMIT;
''')
output=root/args.output;content=''.join(parts)
if args.check:
 if output.read_text()!=content:raise SystemExit('Migration/source drift')
else:
 if output.exists():raise SystemExit('Refusing to overwrite migration')
 output.write_text(content)
