#!/usr/bin/env python3
"""Generate cross-language limits from the single form measurement contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    limit = json.loads((ROOT / 'packages/festapp_contracts/configuration-settings.json').read_text())['unit']['measurement_scripts']['maxLength']
    assert isinstance(limit, int) and limit > 0
    return {
        'web_client/src/components/forms/form_measurement_limits.js':
            f'// Generated by automation/generate_form_measurement_limits.py.\nexport const FORM_MEASUREMENT_SCRIPT_LIMIT = {limit};\n',
        'packages/festapp_core/lib/src/forms/form_measurement_limits.dart':
            f'// Generated by automation/generate_form_measurement_limits.py.\nconst formMeasurementScriptLimit = {limit};\n',
        'database/functions/eshop_forms/form_measurement_limits.sql':
            '-- Generated by automation/generate_form_measurement_limits.py.\n'
            '-- Unit configuration contract owns SQL validation; retire the old Form helper.\n'
            'DROP FUNCTION IF EXISTS public.form_measurement_script_limit_internal();\n',
    }

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for filename, content in outputs().items():
        path = ROOT / filename
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Stale measurement limit: {filename}')
        else:
            path.write_text(content)
