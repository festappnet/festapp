#!/usr/bin/env python3
"""Preserve the applied binding migration and assemble its consent-coverage forward."""
import argparse
import hashlib
from pathlib import Path
from generate_canonical_source_contract import render, TARGET as PARITY

ROOT = Path(__file__).resolve().parents[1]
HISTORICAL = ROOT / 'supabase/migrations/20261114170000_website_consent_bindings.sql'
TARGET = ROOT / 'supabase/migrations/20261115210000_website_consent_live_provider_state.sql'


def forward():
    source = (ROOT / 'database/functions/eshop_forms/website_consent_bindings.sql').read_text()
    parts = ['-- Generated by automation/assemble-website-consent-bindings-migration.py.', 'BEGIN;']
    for name in ('normalize_website_consent_provider_internal', 'save_unit_website_consent_binding'):
        start = source.index('CREATE OR REPLACE FUNCTION public.' + name + '(')
        end = source.index('CREATE OR REPLACE FUNCTION', start + 1)
        parts.append(source[start:end].rstrip())
    # Existing configurations and confirmation receipts retain their restrictions.
    parts.extend(["NOTIFY pgrst, 'reload schema';", 'COMMIT;', ''])
    return '\n'.join(parts)


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if hashlib.sha256(HISTORICAL.read_bytes()).hexdigest() != '2e1b565e386b3b2fd85cff7bfa82ea9dba22eb867a7121dc382738f163a7fecd':
    raise SystemExit('Immutable website consent migration changed')
if args.check:
    if TARGET.read_text() != forward():
        raise SystemExit('Website consent forward migration is stale')
    if PARITY.read_text() != render():
        raise SystemExit('Current canonical source parity is stale')
    print('Website consent history, forward and source parity verified')
else:
    TARGET.write_text(forward())
