#!/usr/bin/env python3
"""Forward migration for server-owned CMS consent configuration."""
import argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'supabase/migrations/20261114170000_website_consent_bindings.sql'
base='database/functions/eshop_forms/'
policy=(ROOT/(base+'form_measurement_policy.sql')).read_text()
bindings=(ROOT/(base+'website_consent_bindings.sql')).read_text()
# Table first, shared semantic owner second, then dependent projections/RPCs.
cut=bindings.index('CREATE OR REPLACE FUNCTION')
a=policy.index('-- One semantic notice owner')
b=policy.index('-- consent_required denotes')
text='-- Generated by automation/assemble-website-consent-bindings-migration.py.\nBEGIN;\n'+bindings[:cut]+policy[a:b]+bindings[cut:]+policy+'\n'+(ROOT/(base+'form_measurement_runtime.sql')).read_text()+"\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
if parser.parse_args().check:
 if not TARGET.exists() or TARGET.read_text()!=text: raise SystemExit('Website consent migration is stale')
else: TARGET.write_text(text)
