import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const policy = JSON.parse(readFileSync(new URL('shared/html/app-content-policy.json', root), 'utf8'));
const quote = value => {
    if (!/^[a-z0-9-]+$/.test(value)) throw new Error(`Invalid HTML policy token: ${value}`);
    return `'${value}'`;
};
const set = values => `<String>{${values.map(quote).join(', ')}}`;
const comment = '// Generated by automation/generate_html_content_policy.mjs. Do not edit.\n';
const dart = comment + ['removedProperties', 'removedAttributes', 'removedElements', 'blockElements']
    .map(key => `const appHtml${key[0].toUpperCase() + key.slice(1)} = ${set(policy[key])};\n`).join('') +
    'const appHtmlEmphasis = <({String tag, String property, Set<String> values})>[\n' +
    policy.emphasis.map(rule => `  (tag: ${quote(rule.tag)}, property: ${quote(rule.property)}, values: ${set(rule.values)}),`).join('\n') + '\n];\n';
const outputs = new Map([
    ['lib/components/html/app_content_policy.g.dart', dart],
    ['web_client/src/utils/app_content_policy.g.js', comment + `export const appHtmlPolicy = ${JSON.stringify(policy, null, 4)};\n`],
]);
for (const [path, content] of outputs) {
    const url = new URL(path, root);
    if (process.argv.includes('--check')) {
        if (readFileSync(url, 'utf8') !== content) throw new Error(`Stale generated file: ${path}`);
    } else writeFileSync(url, content);
}
