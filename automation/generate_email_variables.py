#!/usr/bin/env python3
"""Generate canonical authoring metadata from one email-variable catalog."""
import json
import sys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = json.loads((ROOT / 'packages/festapp_contracts/email-variables.json').read_text())
variables = spec['variables']
assert all(len(codes) == len(set(codes)) and set(codes) <= variables.keys() for codes in spec['templates'].values())
banner = 'Generated by automation/generate_email_variables.py; edit packages/festapp_contracts/email-variables.json.'
js = json.dumps(spec, ensure_ascii=False, indent=2)
dart_kinds = '\n'.join(f"  '{code}': EmailValueKind.{value['kind']}," for code, value in variables.items())
dart_unique = ', '.join(repr(code) for code, value in variables.items() if not value['repeatable'])
dart_blocks = ', '.join(repr(code) for code, value in variables.items() if value.get('bodyBlock'))
dart_html = ', '.join(repr(code) for code, value in variables.items() if value['html'])
renames = json.loads((ROOT / 'automation/email-template-cutover/renames.json').read_text())
assert set(renames).isdisjoint(variables)
assert set(renames.values()) <= variables.keys()
retired = '|'.join(re.escape(code) for code in renames)
retired_pattern = r'\{\{\s*(' + retired + r')\s*\}\}'
outputs = {
    'supabase/functions/_shared/emailVariables.ts': f'''// {banner}
export const emailVariableContract = {js} as const;
export const emailVariablePattern = new RegExp(emailVariableContract.tokenPattern, 'g');
const retiredEmailVariablePattern = new RegExp({json.dumps(retired_pattern)});

/** Reject the retired format; no legacy name is interpreted or converted. */
export function assertCanonicalEmailTemplate(value: string | null | undefined): void {{
  if (value != null && retiredEmailVariablePattern.test(value)) {{
    throw new Error('noncanonical_email_template');
  }}
}}

''',
    'packages/festapp_core/lib/src/email_templates/email_variables.dart': f'''// {banner}
enum EmailValueKind {{ text, url, richInline, richBlock }}

const emailVariablePattern = r'{spec['tokenPattern']}';
final _retiredEmailVariablePattern = RegExp(r'{retired_pattern}');
void assertCanonicalEmailTemplate(String? value) {{
  if (value != null && _retiredEmailVariablePattern.hasMatch(value)) {{
    throw StateError('noncanonical_email_template');
  }}
}}
const emailTemplateVariables = <String, List<String>>{json.dumps(spec['templates'], ensure_ascii=False, indent=2)};
const emailVariableKinds = <String, EmailValueKind>{{
{dart_kinds}
}};
const nonRepeatableEmailVariables = <String>{{{dart_unique}}};
const htmlEmailVariables = <String>{{{dart_html}}};
const bodyBlockEmailVariables = <String>{{{dart_blocks}}};

''',
}
outputs['database/functions/others/email_variable_contract.sql'] = r'''-- Generated by automation/generate_email_variables.py. Retired placeholders are rejected, never translated.
CREATE OR REPLACE FUNCTION public.email_template_variables_are_canonical(p_text text)
RETURNS boolean LANGUAGE sql IMMUTABLE SET search_path=public,extensions AS $$
 SELECT coalesce(p_text !~ '\{\{[[:space:]]*(''' + retired + r''')[[:space:]]*\}\}',true);
$$;
CREATE OR REPLACE FUNCTION public.email_template_overrides_are_canonical(p_overrides jsonb)
RETURNS boolean LANGUAGE sql IMMUTABLE SET search_path=public,extensions AS $$
 SELECT NOT EXISTS(SELECT 1 FROM jsonb_each(CASE WHEN jsonb_typeof(p_overrides)='object'
   THEN p_overrides ELSE '{}'::jsonb END) item
  WHERE NOT public.email_template_variables_are_canonical(item.value->>'subject')
     OR NOT public.email_template_variables_are_canonical(item.value->>'html'));
$$;
REVOKE ALL ON FUNCTION public.email_template_variables_are_canonical(text),public.email_template_overrides_are_canonical(jsonb)
 FROM PUBLIC,anon,authenticated,service_role;
GRANT EXECUTE ON FUNCTION public.email_template_variables_are_canonical(text),public.email_template_overrides_are_canonical(jsonb)
 TO service_role;
'''
waitlist = json.loads((ROOT / 'packages/festapp_contracts/waitlist-email-copy.json').read_text())
copy = waitlist['tones']
tones = json.loads((ROOT / 'packages/festapp_contracts/communication-tone.json').read_text())['values']
assert set(copy) == set(tones)
assert all(set(value) == set(copy[tones[0]]) for value in copy.values())
outputs['supabase/functions/_shared/waitlistEmailCopy.ts'] = (
    '// Generated by automation/generate_email_variables.py from packages/festapp_contracts/waitlist-email-copy.json.\n'
    + 'export const waitlistEmailCopy = ' + json.dumps(copy, ensure_ascii=False, indent=2) + ' as const;\n'
    + 'const countForms = ' + json.dumps(waitlist['countForms'], ensure_ascii=False) + ' as const;\n'
    + '''export function waitlistCountPhrase(count: number, noun: keyof typeof countForms): string {
  const forms = countForms[noun];
  return `${count} ${forms[count === 1 ? 0 : count >= 2 && count <= 4 ? 1 : 2]}`;
}
'''
)
outputs['packages/festapp_core/lib/src/email_templates/waitlist_email_copy.dart'] = (
    '// Generated by automation/generate_email_variables.py from packages/festapp_contracts/waitlist-email-copy.json.\n'
    + 'const _countForms = <String, List<String>>' + json.dumps(waitlist['countForms'], ensure_ascii=False) + ';\n'
    + '''String waitlistCountPhrase(int count, String noun) {
  final forms = _countForms[noun]!;
  return '$count ${forms[count == 1 ? 0 : count >= 2 && count <= 4 ? 1 : 2]}';
}
'''
)
outputs['database/functions/eshop_waitlist/email_copy.sql'] = '''-- Generated by automation/generate_email_variables.py from packages/festapp_contracts/waitlist-email-copy.json.
CREATE OR REPLACE FUNCTION public.get_waitlist_email_tone_substitutions_internal(p_form bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path=public,extensions AS $$
 SELECT $copy$''' + json.dumps(copy, ensure_ascii=False, separators=(',', ':')) + '''$copy$::jsonb
   -> public.resolve_communication_tone(public.get_effective_form_data(p_form)->>'communication_tone');
$$;
REVOKE ALL ON FUNCTION public.get_waitlist_email_tone_substitutions_internal(bigint)
 FROM PUBLIC,anon,authenticated,service_role;
'''
for name, content in outputs.items():
    content = content.rstrip() + '\n'
    path = ROOT / name
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit('Email-variable contract is stale: ' + name)
    else:
        path.write_text(content)
