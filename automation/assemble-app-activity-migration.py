#!/usr/bin/env python3
"""Generate the forward public-news/app-notification fix; installed migrations stay immutable."""
from pathlib import Path
import argparse
root = Path(__file__).resolve().parents[1]
sources = [
    'security/news_read_marker.sql', 'others/get_news_read_state.sql',
    'notification_center/app_activity.sql', 'notification_center/core.sql',
    'notification_center/maintenance.sql', 'users/occasion_enrolment_internal.sql',
    'events/set_event_attendance_client_sync_v1.sql',
    'events/save_event_domain_command_internal_v1.sql',
]
text = '-- Generated by automation/assemble-app-activity-migration.py\nBEGIN;\n'
for name in sources:
    source = (root / 'database/functions' / name).read_text()
    if name == 'notification_center/maintenance.sql':
        source = source[source.index('CREATE OR REPLACE FUNCTION'):]
    text += f'\n-- SOURCE: {name}\n{source}\n'
text += "NOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
output = root / 'supabase/migrations/20261024190000_public_news_app_notifications.sql'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not output.exists() or output.read_text() != text:
        raise SystemExit('App activity migration differs from canonical sources')
    print('App activity migration matches canonical sources')
else:
    output.write_text(text)
    print(output.relative_to(root))
