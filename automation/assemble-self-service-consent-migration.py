#!/usr/bin/env python3
"""Assemble self-service consent from canonical SQL and automatic manager-owned website origins."""
import argparse
from pathlib import Path
from generate_canonical_source_contract import render, TARGET as PARITY
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'supabase/migrations/20261117160000_self_service_website_consent.sql'
FUNCTIONS = {
    'others/configuration_settings_contract.sql': ['configuration_settings_contract_internal_v1'],
    'others/configuration_settings.sql': ['validate_configuration_value_internal_v1'],
    'eshop_forms/website_consent_bindings.sql': ['website_consent_binding_effective_internal', 'website_consent_bindings_policy_internal', 'get_unit_website_consent_bindings'],
    'eshop_forms/form_measurement_support.sql': ['form_measurement_runtime_supported_internal'],
    'eshop_forms/form_measurement_policy.sql': ['unit_measurement_parent_origins_internal', 'form_measurement_runtime_internal'],
    'user_permissions/form_measurement.sql': ['can_read_form_measurement_runtime'],
    'eshop_forms/form_measurement_runtime.sql': ['get_form_measurement_runtime_config'],
    'eshop_forms/unit_measurement_approval.sql': ['unit_measurement_approval_internal'],
    'emails/email_queue.sql': ['email_intent_valid'],
}
def forward():
    parts = ['-- Generated by automation/assemble-self-service-consent-migration.py.', 'BEGIN;']
    for path, names in FUNCTIONS.items():
        source = (ROOT / 'database/functions' / path).read_text()
        for name in names:
            start = source.index('CREATE OR REPLACE FUNCTION public.' + name + '(')
            end = source.find('CREATE OR REPLACE FUNCTION', start + 1)
            parts.append(source[start:end if end >= 0 else len(source)].rstrip())
    return '\n'.join(parts + ["NOTIFY pgrst, 'reload schema';", 'COMMIT;', ''])
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if TARGET.read_text() != forward():
        raise SystemExit('Self-service consent migration is stale')
    if PARITY.read_text() != render():
        raise SystemExit('Canonical source parity is stale')
    print('Self-service consent migration and source parity verified')
else:
    TARGET.write_text(forward())
