import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('shared/email/iana-tlds.txt', root), 'utf8');
const [header, ...lines] = source.trimEnd().split(/\r?\n/);
if (!/^# Version \d{10}, Last Updated .+ UTC$/.test(header)) throw new Error('Invalid IANA version header');
if (lines.length < 1000 || lines.some(tld => !/^(?:[A-Z]{2,63}|XN--[A-Z0-9-]{1,59})$/.test(tld)) || new Set(lines).size !== lines.length || lines.join('\n') !== [...lines].sort().join('\n')) {
    throw new Error('Incomplete, malformed, duplicate or unsorted IANA snapshot');
}
const values = lines.map(line => line.toLowerCase());
const comment = `// Generated by automation/generate_email_tlds.mjs. Do not edit.\n// ${header.slice(2)}\n`;
const outputs = new Map([
    ['web_client/src/logic/email_tlds.g.js', `${comment}export const emailTlds = new Set([\n${values.map(value => `    '${value}',`).join('\n')}\n]);\n`],
    ['packages/festapp_core/lib/src/forms/email_tlds.g.dart', `${comment}const emailTlds = <String>{\n${values.map(value => `  '${value}',`).join('\n')}\n};\n`],
]);
// Validate every input before writing either output. --check is offline/read-only.
for (const [path, content] of outputs) {
    const url = new URL(path, root);
    if (process.argv.includes('--check')) {
        if (readFileSync(url, 'utf8') !== content) throw new Error(`Stale generated file: ${fileURLToPath(url)}`);
    } else writeFileSync(url, content);
}
