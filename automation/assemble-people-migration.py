#!/usr/bin/env python3
"""Freeze stage 6 canonical owners and named profile contract in a new migration."""
import migration_inputs
from pathlib import Path
import json,re,sys,hashlib
root=Path(__file__).resolve().parents[1]
contract=json.dumps(json.loads(migration_inputs.read_text(root/'packages/festapp_contracts/people-settings.json')),separators=(',',':'))
profile=root/'database/functions/people/profile_changes.sql'
profile_sql=re.sub(r'\$contract\$.*?\$contract\$',lambda _: '$contract$'+contract+'$contract$',migration_inputs.read_text(profile),flags=re.S)
sources=['people/access_fanout.sql','people/scope.sql','people/profile_changes.sql','units/begin_unit_client_mutation_v1.sql','users/update_unit_user.sql','people/unit_user_command.sql','users/unit_access_deletion.sql','users/get_all_users_from_unit.sql','users/save_profile_client_sync_v1.sql','users/create_occasion_user_client_sync_v1.sql','groups/adjacent_group_lifecycle.sql','groups/save_user_group_client_sync_v1.sql','groups/delete_user_group_client_sync_v1.sql','groups/add_user_group_members_client_sync_v1.sql','groups/replace_group_assignments_client_sync_v1.sql','users/import_users_from_tickets_client_sync_v1.sql','people/authoring.sql']
content='-- Generated by automation/assemble-people-migration.py. Stage 6.\n'+'\n\n'.join('-- Source: database/functions/'+p+'\n'+(profile_sql if p=='people/profile_changes.sql' else migration_inputs.read_text(root/'database/functions'/p)) for p in sources)
target=root/'supabase/migrations/20261027150000_people_group_authoring.sql'
if '--check' in sys.argv:
 if hashlib.sha256(target.read_bytes()).hexdigest()!='d05896f59bcb8abe7e2dc46848ffcf67381d86d23338d21571e45b8066d216d0':raise SystemExit('Installed people migration bytes changed')
 # Installed migration bytes remain frozen; later forward owners supersede
 # membership primitives without rewriting the applied stage-6 migration.
 from generate_canonical_source_contract import definitions
 effective={}
 for migration in sorted(migration_inputs.migration_paths((root/'supabase/migrations').parent.parent)):
  for signature,body in definitions(migration_inputs.read_text(migration)):
   if isinstance(body,tuple):
    if signature in effective: effective[body[1]]=effective.pop(signature)
   elif body is None: effective.pop(signature,None)
   else: effective[signature]=body
 for source in sources:
  for signature,body in definitions(migration_inputs.read_text(root/'database/functions'/source)):
   if body is not None and not isinstance(body,tuple) and effective.get(signature)!=body:
    raise SystemExit('People source differs from effective migration head: '+signature)
 if migration_inputs.read_text(profile)!=profile_sql:raise SystemExit('People contract differs from canonical JSON')
else:
 if migration_inputs.exists(target): raise SystemExit('Installed migration is immutable; use a scoped forward assembler')
 migration_inputs.write_text(profile, profile_sql);migration_inputs.write_text(target, content)
