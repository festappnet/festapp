#!/usr/bin/env python3
"""Definition-only canonical operations release; historical migrations are frozen."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'automation/operations-foundation-sources.json'


def assemble():
    manifest = json.loads(MANIFEST.read_text())
    if manifest['migration'] != 'supabase/migrations/20261021110000_order_seating_source_parity.sql':
        raise SystemExit('Refusing a historical or unreviewed operations migration target')
    if (ROOT / manifest['migration']).is_symlink():
        raise SystemExit('Refusing a symlink migration target')
    sources = manifest['forwardSources']
    if not set(sources).issubset(manifest['sources']):
        raise SystemExit('Forward sources must belong to the canonical operations inventory')
    if len(sources) != len(set(sources)):
        raise SystemExit('Duplicate source in operations manifest')
    text = '-- Generated by automation/assemble-operations-foundation-migration.py.\n'
    text += '-- Forward definitions only; never replay historical adoption.\nBEGIN;\n'
    for source in sources:
        path = ROOT / 'database/functions' / source
        if not path.resolve().is_relative_to((ROOT / 'database/functions').resolve()):
            raise SystemExit('Source outside authored SQL')
        text += f'\n-- Source: database/functions/{source}\n{path.read_text().rstrip()}\n'
    return ROOT / manifest['migration'], text + '\nCOMMIT;\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    target, sql = assemble()
    if args.output and args.output.resolve() != target.resolve():
        raise SystemExit('Refusing another migration target; historical SQL is immutable')
    if args.check:
        if not target.exists():
            raise SystemExit('Operations migration is missing')
        if target.read_text() != sql:
            manifest = json.loads(MANIFEST.read_text())
            covered = {}
            for successor in manifest.get('forwardSuccessors', []):
                release = json.loads((ROOT / successor).read_text())
                release_sql = (ROOT / release['migration']).read_text()
                if release['migration'] <= manifest['migration']:
                    raise SystemExit('Successor must be a newer forward migration')
                assembler = release.get('assembler')
                if assembler:
                    assembler_path = ROOT / assembler
                    if not assembler_path.resolve().is_relative_to((ROOT / 'automation').resolve()) or assembler_path.is_symlink():
                        raise SystemExit('Invalid successor assembler')
                    subprocess.run(['python3', str(assembler_path), '--check'], check=True, cwd=ROOT)
                for source in release['sources']:
                    if not assembler and f'-- Source: {source}\n' + (ROOT / source).read_text().rstrip() not in release_sql:
                        raise SystemExit('Successor differs from canonical source: ' + source)
                    covered[source.removeprefix('database/functions/')] = True
            for source in manifest['forwardSources']:
                if source not in covered and (ROOT / 'database/functions' / source).read_text().rstrip() not in target.read_text():
                    raise SystemExit('Operations source lacks effective forward ownership: ' + source)
    else:
        if json.loads(MANIFEST.read_text()).get('forwardSuccessors'):
            raise SystemExit('This historical target is superseded; assemble the current forward successor')
        if args.output is None:
            raise SystemExit('Writing requires --output with the explicit forward manifest target')
        target.write_text(sql)


if __name__ == '__main__':
    main()
