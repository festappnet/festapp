import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { initReferenceCarousels } from '../../src/marketing/reference_carousel.js';

test('reference gallery supports paging, keyboard boundaries and reduced motion without taking focus from event links', async () => {
    const dom = new JSDOM(`<script type="application/json" id="marketing-ui">{"position":"{first}-{last} z {count} akcí","total":"{count} akcí"}</script><div data-reference-carousel><div data-reference-track tabindex="0">${Array.from({length:6}, (_,i)=>`<a class="reference-card" href="/event-${i}">Ples ${i}</a>`).join('')}</div><div data-reference-controls hidden><p data-reference-position></p><button data-reference-previous>Předchozí</button><button data-reference-next>Další</button></div></div>`);
    const { window: win } = dom;
    const doc = win.document;
    const track = doc.querySelector('[data-reference-track]');
    const back = doc.querySelector('[data-reference-previous]');
    const next = doc.querySelector('[data-reference-next]');
    let reduced = false;
    let lastBehavior;
    win.matchMedia = () => ({get matches() {return reduced;}});
    Object.defineProperties(track, {clientWidth:{value:900},scrollWidth:{value:1800}});
    track.getBoundingClientRect = () => ({left:0,right:900});
    [...track.children].forEach((card,i) => {card.getBoundingClientRect = () => ({left:i*300-track.scrollLeft,right:i*300+280-track.scrollLeft,width:280});});
    const move = ({left,behavior},relative) => {
        lastBehavior = behavior;
        track.scrollLeft = Math.max(0,Math.min(900,(relative?track.scrollLeft:0)+left));
        track.dispatchEvent(new win.Event('scroll'));
    };
    track.scrollBy = options => move(options,true);
    track.scrollTo = options => move(options,false);
    const cleanup = initReferenceCarousels(doc);
    const settle = () => new Promise(resolve => win.setTimeout(resolve,180));
    assert.equal(back.disabled,true);
    assert.equal(back.hidden,true);
    assert.equal(next.hidden,false);
    assert.equal(next.disabled,false);
    assert.equal(doc.querySelector('[data-reference-controls]').hidden,false);
    next.click(); await settle();
    assert.equal(track.scrollLeft,900);
    assert.equal(lastBehavior,'smooth');
    assert.equal(next.disabled,true);
    assert.equal(back.disabled,false);
    assert.equal(next.hidden,true);
    assert.equal(back.hidden,false);
    assert.equal(doc.querySelector('[data-reference-position]').textContent,'4-6 z 6 akcí');
    reduced = true;
    track.dispatchEvent(new win.KeyboardEvent('keydown',{key:'Home',bubbles:true,cancelable:true}));
    await settle();
    assert.equal(track.scrollLeft,0);
    assert.equal(lastBehavior,'instant');
    assert.equal(back.hidden,true);
    assert.equal(next.hidden,false);
    const link = track.querySelector('a'); link.focus();
    link.dispatchEvent(new win.KeyboardEvent('keydown',{key:'End',bubbles:true,cancelable:true}));
    assert.equal(track.scrollLeft,0,'event link key presses are not hijacked');
    assert.equal(doc.activeElement,link);
    cleanup();
    next.click(); assert.equal(track.scrollLeft,0);
    dom.window.close();
});
