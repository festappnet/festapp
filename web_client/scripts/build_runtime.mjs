import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import startup from '../../automation/lib/startup_theme.cjs';
const root = new URL('../../', import.meta.url);
const result = await build({absWorkingDir:new URL('../', import.meta.url).pathname,
    entryPoints:['src/runtime/update_entry.js'], bundle:true, format:'iife', write:false,
    legalComments:'none', target:'es2022'});
const output = '// Generated by web_client/scripts/build_runtime.mjs from src/runtime/update_entry.js.\n' + result.outputFiles[0].text;
const target = new URL('web/festapp_update_prompt.js', root);
const check = process.argv.includes('--check');
if (check) {
    if (await readFile(target, 'utf8') !== output) throw new Error('Update runtime differs from its module sources');
} else await writeFile(target, output);
startup.configureStartupThemes(root.pathname, {check});
