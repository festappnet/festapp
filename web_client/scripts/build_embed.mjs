import writer from '../../automation/lib/write_if_changed.cjs';
import {build} from 'esbuild';
import {readFile} from 'node:fs/promises';
const result = await build({absWorkingDir:new URL('../', import.meta.url).pathname,
    entryPoints:['src/embed/host.js'], bundle:true, format:'iife', write:false,
    legalComments:'none', target:'es2022'});
const output = '// Generated by scripts/build_embed.mjs from src/embed/host.js.\n' + result.outputFiles[0].text;
const target = new URL('../public/embed.js', import.meta.url);
if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('embed.js differs from its module sources');
} else writer.writeFileSync(target, output);
