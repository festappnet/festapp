import {readFile, writeFile} from 'node:fs/promises';
const template = await readFile(new URL('./embed.template.js', import.meta.url), 'utf8');
const contract = await readFile(new URL('../src/components/forms/form_measurement_contract.js', import.meta.url), 'utf8');
const consent = await readFile(new URL('../src/components/forms/form_measurement_consent.js', import.meta.url), 'utf8');
const output = '// Generated by scripts/build_embed.mjs. Edit the template or shared contract.\n' +
 template.replace('    /* MEASUREMENT_CONSENT */', consent.replaceAll('export ', ''))
 .replace('    /* MEASUREMENT_CONTRACT */', contract.replaceAll('export ', '').split('\n').map(line => line ? '    ' + line : '').join('\n'));
const target = new URL('../public/embed.js', import.meta.url);
if (process.argv.includes('--check')) {
 if (await readFile(target, 'utf8') !== output) throw new Error('embed.js differs from shared measurement contract');
} else await writeFile(target, output);
