import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../../',import.meta.url);
const result=await build({absWorkingDir:new URL('web_client/',root).pathname,entryPoints:[new URL('workers/form-measurement/src/bootstrap.js',root).pathname],bundle:true,format:'iife',write:false,legalComments:'none',target:'es2022'});
const source='// Generated by web_client/scripts/build_measurement_runtime.mjs.\nexport const runtimeSource = '+JSON.stringify(result.outputFiles[0].text)+';\n';
const target=new URL('workers/form-measurement/src/runtime_source.mjs',root);
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==source)throw Error('Measurement runtime bundle differs from source');
}else await writeFile(target,source);
if(process.argv.includes('--pages')){
 const directory=new URL('workers/form-measurement/dist/',root);await mkdir(directory,{recursive:true});
 await build({absWorkingDir:new URL('web_client/',root).pathname,entryPoints:[new URL('workers/form-measurement/src/worker.mjs',root).pathname],bundle:true,format:'esm',outfile:new URL('_worker.js',directory).pathname,target:'es2022'});
 await writeFile(new URL('_routes.json',directory),JSON.stringify({version:1,include:['/*'],exclude:[]}));
}
