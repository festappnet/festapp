-- Per-occasion place categories (optional icon; at most one default per occasion).
-- The "toilet" category drives the Cleaning service map/tiles. RLS: public read,
-- editor write (see database/policies/02_policies.sql).
CREATE TABLE IF NOT EXISTS public.place_types (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occasion    bigint NOT NULL REFERENCES public.occasions(id),
  code        text NOT NULL,
  title       text NOT NULL,
  icon        bigint REFERENCES public.icons(id),
  "order"     bigint,
  is_hidden   boolean NOT NULL DEFAULT false,
  is_default  boolean NOT NULL DEFAULT false,
  created_at  timestamptz DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT place_types_occasion_code_unique UNIQUE (occasion, code)
);
CREATE UNIQUE INDEX IF NOT EXISTS place_types_one_default_per_occasion
  ON public.place_types USING btree (occasion) WHERE (is_default = true);

-- Cleaning service: toilet-status reports (feature "cleaning"). All writes go
-- through SECURITY DEFINER RPCs (report_cleaning_issue / resolve_cleaning_place);
-- RLS allows direct SELECT to editors only, crew reads via get_cleaning_reports.
create table if not exists public.cleaning_reports (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  occasion     BIGINT NOT NULL,
  place        BIGINT NOT NULL,
  problem_type TEXT NOT NULL,
  note         TEXT NULL,
  created_by   UUID NULL DEFAULT auth.uid(),
  created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  resolved_by  UUID NULL,
  resolved_at  TIMESTAMP WITH TIME ZONE NULL,
  data         JSONB NULL,
  CONSTRAINT cleaning_reports_pkey PRIMARY KEY (id),
  CONSTRAINT cleaning_reports_occasion_fkey FOREIGN KEY (occasion) REFERENCES public.occasions (id),
  CONSTRAINT cleaning_reports_place_fkey FOREIGN KEY (place) REFERENCES public.places (id) ON DELETE CASCADE,
  CONSTRAINT cleaning_reports_created_by_fkey FOREIGN KEY (created_by) REFERENCES public.user_info (id),
  CONSTRAINT cleaning_reports_resolved_by_fkey FOREIGN KEY (resolved_by) REFERENCES public.user_info (id),
  -- problem_type list kept in sync with: report_cleaning_issue.sql,
  -- CleaningStatusHelper (cleaning_status.dart), cleaning_report_dialog.dart.
  CONSTRAINT cleaning_reports_problem_type_check CHECK (problem_type = ANY (ARRAY['paper'::text, 'hygiene'::text, 'contamination'::text]))
) TABLESPACE pg_default;

-- Open reports per place drive the derived toilet status (highest severity wins).
CREATE INDEX IF NOT EXISTS cleaning_reports_open_idx
  ON public.cleaning_reports USING btree (place, problem_type)
  WHERE resolved_at IS NULL;

