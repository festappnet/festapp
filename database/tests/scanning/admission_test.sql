DO $$
DECLARE oc bigint; h bigint; tid bigint; symbol text; session jsonb; sid uuid; token text; dto jsonb; op jsonb; r jsonb; snap jsonb; original jsonb; fx jsonb; editor uuid:=gen_random_uuid();
BEGIN
 fx:=public.scanner_test_fixture();oc:=(fx->>'occasion')::bigint;tid:=(fx#>>'{tickets,0}')::bigint;SELECT ticket_symbol INTO symbol FROM eshop.tickets WHERE id=tid;
 PERFORM assert_not_null(tid,'fixture has an eligible ticket');
 INSERT INTO public.occasions_hidden(secret) VALUES('SCANNER_TEST_ONLY_20261018') RETURNING id INTO h;
 UPDATE public.occasions SET occasion_hidden=h WHERE id=oc;
 session:=public.open_scanner_session('SCANNER_TEST_ONLY_20261018',NULL,'Test');
 PERFORM assert_eq(session->>'code','200','session opened');
 sid:=(session#>>'{data,session_id}')::uuid;token:=session#>>'{data,token}';
 r:=public.lookup_scanner_ticket(sid,token,symbol);dto:=r->'data';
 PERFORM assert_eq(r->>'code','200','lookup is scoped and available');
 PERFORM assert_true(NOT(dto ? 'order'),'minimal projection excludes full order');
 op:=jsonb_build_object('operation_id',gen_random_uuid(),'origin_session_id',sid,'ticket_id',tid,'action','admit_ticket','snapshot_id',NULL,'settings_revision',r->'settings_revision','eligibility_fingerprint',dto->'eligibility_fingerprint','confirm_unpaid',false,'captured_at',clock_timestamp());
 snap:=public.prepare_scanner_snapshot(sid,token);PERFORM assert_eq(snap->>'code','200','snapshot created');
 PERFORM assert_true((snap#>>'{data,ticket_count}')::bigint>0,'nonempty snapshot');
 r:=public.sync_scanner_operations(sid,token,jsonb_build_array(op));
 PERFORM assert_eq(r#>>'{data,0,outcome}','accepted','first operation accepted');original:=r#>'{data,0}';
 r:=public.sync_scanner_operations(sid,token,jsonb_build_array(op));
 PERFORM assert_true((r#>>'{data,0,replayed}')::boolean,'lost response retry returns receipt');
 INSERT INTO auth.users(id,email) VALUES(editor,editor||'@scanner.invalid');
 INSERT INTO public.user_info(id,name,organization) SELECT editor,'Scanner editor',organization FROM public.occasions WHERE id=oc;
 INSERT INTO public.occasion_users(occasion,"user",is_editor_order) VALUES(oc,editor,true);
 PERFORM set_config('request.jwt.claim.sub',editor::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',editor,'role','authenticated')::text,true);
 PERFORM public.update_ticket_to_unused_ws(tid);
 r:=public.sync_scanner_operations(sid,token,jsonb_build_array(op));
 PERFORM assert_eq((SELECT state FROM eshop.tickets WHERE id=tid),'sent','historical receipt cannot re-use admin unused ticket');
 PERFORM assert_eq((r#>'{data,0}')-'replayed',original,'historical receipt immutable');
 op:=jsonb_set(op,'{operation_id}',to_jsonb(gen_random_uuid()));
 r:=public.sync_scanner_operations(sid,token,jsonb_build_array(op));
 PERFORM assert_eq(r#>>'{data,0,reason}','eligibility_changed','old snapshot generation cannot admit reopened ticket');
 r:=public.sync_scanner_operations(sid,token,jsonb_build_array(op||jsonb_build_object('confirm_unpaid',true)));
 PERFORM assert_eq(r#>>'{data,0,reason}','operation_payload_mismatch','same ID different payload rejected');
 r:=public.get_scanner_summary(sid,token);
 PERFORM assert_eq((r#>>'{data,used_current}')::bigint+(r#>>'{data,unused_eligible}')::bigint,(r#>>'{data,eligible_total}')::bigint,'truthful denominator');
 r:=public.update_ticket_to_used((fx#>>'{tickets,1}')::bigint,'SCANNER_TEST_ONLY_20261018');
 PERFORM assert_eq(r->>'code','200','retained native admission signature works');
 r:=public.update_ticket_to_used((fx#>>'{tickets,1}')::bigint,'SCANNER_TEST_ONLY_20261018');
 PERFORM assert_eq(r->>'code','409','native repeat never writes twice');
 PERFORM public.update_ticket_to_used_ws(tid);
 PERFORM assert_eq((SELECT state FROM eshop.tickets WHERE id=tid),'used','admin used wrapper retains signature and parent locks');
 r:=public.update_scan_code((SELECT link FROM public.occasions WHERE id=oc),'ROTATED_SCANNER_TEST_ONLY');
 PERFORM assert_eq(r->>'code','200','native scan-code rotation keeps signature');
 BEGIN PERFORM public.get_scanner_summary(sid,token);PERFORM assert_fail('rotation invalidates old epoch');EXCEPTION WHEN SQLSTATE 'PT401' THEN NULL;END;
 PERFORM public.revoke_scanner_session(sid,token);
 BEGIN PERFORM public.lookup_scanner_ticket(sid,token,symbol);PERFORM assert_fail('revoked session');EXCEPTION WHEN SQLSTATE 'PT401' THEN NULL;END;
 r:=public.get_scanner_receipts(sid,token,ARRAY[(original->>'operation_id')::uuid]);PERFORM assert_eq(jsonb_array_length(r->'data'),1,'revoked session can reconcile original receipts');
END $$;
