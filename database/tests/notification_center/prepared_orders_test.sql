BEGIN;
DO $$
DECLARE org bigint;oc bigint;viewer uuid:=gen_random_uuid();colleague uuid:=gen_random_uuid();hidden uuid:=gen_random_uuid();
 ids bigint[]:='{}';oid bigint;v jsonb;first_view jsonb;whole_view jsonb;item jsonb;scope jsonb;token uuid;unseen bigint;pending integer;
BEGIN
 INSERT INTO public.organizations(title) VALUES('Prepared order contract') RETURNING id INTO org;
 INSERT INTO auth.users(id) VALUES(viewer),(colleague),(hidden);
 INSERT INTO public.user_info(id,organization,email_readonly) VALUES(viewer,org,'viewer@example.invalid'),(colleague,org,'colleague@example.invalid'),(hidden,org,'buyer1@example.invalid');
 INSERT INTO public.occasions(organization,title,link,start_time,end_time) VALUES(org,'Orders',gen_random_uuid()::text,now(),now()+interval '1 day') RETURNING id INTO oc;
 INSERT INTO public.occasion_users(occasion,"user",is_editor_order_view) VALUES(oc,viewer,true),(oc,colleague,true);
 INSERT INTO public.notification_center_organizations(organization,initialized_at) VALUES(org,now()-interval '60 days');
 FOR i IN 1..3 LOOP
  INSERT INTO eshop.orders(occasion,state,order_symbol,order_sequence,data) VALUES(oc,'ordered',public.generate_order_symbol(),i,jsonb_build_object('name','Buyer '||i,'email','buyer'||i||'@example.invalid')) RETURNING id INTO oid;
  ids:=array_append(ids,oid);
 END LOOP;
 PERFORM public.notification_center_publish_internal(org,oc,'order_created','prepared:1',jsonb_build_object('orderId',ids[1],'count',2,'formContext',jsonb_build_object('allowsMultiple',true)));
 PERFORM public.project_notification_center(500);
 PERFORM set_config('request.jwt.claim.sub',viewer::text,true);
 v:=public.get_notification_center_view(org,oc);
 PERFORM assert_eq(v->>'state','preparing','initial open never aggregates canonical history');
 PERFORM assert_eq((SELECT seen_through_sequence FROM public.notification_center_user_state WHERE organization=org AND recipient=viewer),0::bigint,'initial preparing cannot acknowledge');
 FOR i IN 1..20 LOOP PERFORM public.prepare_notification_center(100); END LOOP;
 first_view:=public.get_notification_center_view(org,oc,p_mode=>'preview');
 PERFORM assert_eq(first_view->>'state','ready','prepared preview is ready');
 PERFORM assert_eq((SELECT seen_through_sequence FROM public.notification_center_user_state WHERE organization=org AND recipient=viewer),0::bigint,'preview never acknowledges');
 token:=(first_view->>'viewToken')::uuid;
 first_view:=public.get_notification_center_view(org,oc,p_mode=>'open',p_view=>token);
 PERFORM assert_eq(first_view->>'state','ready','explicit open reuses preview token');
 PERFORM assert_eq((first_view#>>'{items,0,data,activityCount}')::int,1,'first order is a complete summary');
 FOR i IN 2..3 LOOP
  PERFORM public.notification_center_publish_internal(org,oc,'order_created','prepared:'||i,jsonb_build_object('orderId',ids[i],'count',CASE WHEN i=3 THEN NULL ELSE 3 END,'formContext',jsonb_build_object('allowsMultiple',true)));
 END LOOP;
 PERFORM public.project_notification_center(500);
 whole_view:=public.get_notification_center_view(org,oc);
 PERFORM assert_eq(whole_view->>'state','ready','incremental delivery needs no historical rebuild');
 PERFORM assert_eq((whole_view#>>'{items,0,data,activityCount}')::int,3,'incremental exact count');
 PERFORM assert_true(whole_view#>'{items,0,data,placeCount}' IS NULL,'unknown places stay unknown');
 PERFORM assert_eq((public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>token)#>>'{items,0,data,activityCount}')::int,1,'token membership excludes arrivals');
 scope:=jsonb_build_object('viewToken',token,'id',first_view#>>'{items,0,id}','organization',org);
 PERFORM assert_true(public.mark_notification_center_view_item_read(org,scope),'another tab reads its captured prefix');
 scope:=jsonb_build_object('viewToken',whole_view->>'viewToken','id',whole_view#>>'{items,0,id}','organization',org);
 PERFORM assert_true(public.mark_notification_center_view_item_read(org,scope),'original tab seals the captured suffix');
 PERFORM assert_true(public.mark_notification_center_view_item_read(org,scope),'reverse retry does not require stale read metadata repair');
 FOR i IN 1..20 LOOP PERFORM public.prepare_notification_center(100);PERFORM public.prepare_notification_center_views(100); END LOOP;
 v:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>(whole_view->>'viewToken')::uuid);
 PERFORM assert_eq(v->>'state','ready','read repair restores existing slots');
 PERFORM assert_eq(v#>>'{items,0,isRead}','true','captured range is now read');
 INSERT INTO public.organization_users(organization,"user",is_hidden) VALUES(org,hidden,true);
 v:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>(whole_view->>'viewToken')::uuid);
 PERFORM assert_eq(v->>'state','preparing','privacy is checked live in one response snapshot');
 PERFORM assert_true(v#>'{items,0,data}' IS NULL,'dirty view exposes no private counters or contacts');
 FOR i IN 1..20 LOOP PERFORM public.prepare_notification_center(100);PERFORM public.prepare_notification_center_views(100); END LOOP;
 v:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>(whole_view->>'viewToken')::uuid);
 PERFORM assert_eq(v->>'state','ready','privacy repair makes the same token usable');
 PERFORM assert_eq((v#>>'{items,0,data,activityCount}')::int,3,'hidden membership does not retract order totals');
 PERFORM assert_eq(jsonb_array_length(public.notification_center_order_selection(oc,scope)),3,'order selection is independent of hidden membership');
 UPDATE public.organization_users SET is_hidden=false WHERE organization=org AND "user"=hidden;
 FOR i IN 1..20 LOOP PERFORM public.prepare_notification_center(100);PERFORM public.prepare_notification_center_views(100); END LOOP;
 v:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>(whole_view->>'viewToken')::uuid);
 PERFORM assert_eq((v#>>'{items,0,data,activityCount}')::int,3,'unhide restores captured contribution');
 UPDATE eshop.orders SET state='storno' WHERE id=ids[1];PERFORM public.notification_center_order_state_internal(ids[1]);
 v:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>(whole_view->>'viewToken')::uuid);
 PERFORM assert_eq(v->>'state','preparing','storno invalidates in its source transaction');
 FOR i IN 1..20 LOOP PERFORM public.prepare_notification_center(100);PERFORM public.prepare_notification_center_views(100); END LOOP;
 v:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>(whole_view->>'viewToken')::uuid);
 PERFORM assert_eq((v#>>'{items,0,data,activityCount}')::int,2,'storno repairs exact frozen count');
 PERFORM assert_eq(jsonb_array_length(public.notification_center_order_selection(oc,scope)),2,'storno repairs selected orders');
 PERFORM assert_eq((SELECT seen_through_sequence FROM public.notification_center_user_state WHERE organization=org AND recipient=colleague),0::bigint,'another recipient is never acknowledged');
END $$;
ROLLBACK;
