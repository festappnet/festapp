BEGIN;
DO $$
DECLARE org bigint; un bigint; oc bigint; bank bigint; pi bigint; oid bigint; tx bigint;
 u uuid:=gen_random_uuid(); dispatch uuid; context jsonb; item jsonb; fingerprint text;
BEGIN
 INSERT INTO public.organizations(title,data) VALUES('Pořadatel','{"DEFAULT_URL":"https://a.example.test"}') RETURNING id INTO org;
 INSERT INTO auth.users(id) VALUES(u);
 INSERT INTO public.user_info(id,organization,email_delivery) VALUES(u,org,'admin@example.test');
 INSERT INTO public.notification_center_organizations(organization,initialized_at) VALUES(org,now()-interval '1 day');
 UPDATE public.email_capacity SET quota_at=now(),daily_quota=100000,allocated_daily=100000;
 PERFORM public.activate_notification_center_emails(org);
 INSERT INTO public.units(organization,title) VALUES(org,'Spolek') RETURNING id INTO un;
 INSERT INTO public.occasions(organization,unit,title,link,start_time,end_time) VALUES(org,un,'Ples',gen_random_uuid()::text,now(),now()+interval '1 day') RETURNING id INTO oc;
 INSERT INTO public.occasion_users(occasion,"user",is_editor_order_view) VALUES(oc,u,true);
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 PERFORM public.save_notification_center_email_settings(org,NULL,0,false,'cs','{"order_payment_received":true}');
 INSERT INTO eshop.bank_accounts(title,type) VALUES('Účet','FIO') RETURNING id INTO bank;
 INSERT INTO eshop.unit_bank_accounts(unit,bank_account) VALUES(un,bank);
 INSERT INTO eshop.payment_info(variable_symbol,amount,currency_code,bank_account,paid,deposit_amount) VALUES(100,100,'CZK',bank,0,20) RETURNING id INTO pi;
 INSERT INTO eshop.orders(occasion,payment_info,state,price,currency_code,order_symbol,order_sequence,data)
 VALUES(oc,pi,'ordered',100,'CZK',public.generate_order_symbol(),1,'{"name":"Jana","surname":"Nováková","email":"jana@example.test"}') RETURNING id INTO oid;
 INSERT INTO eshop.transactions(amount,currency,bank_account_id,date,transaction_type) VALUES(20,'CZK',bank,now(),'manual') RETURNING id INTO tx;
 PERFORM public.apply_transaction_pairing(tx,pi,'test','system');
 PERFORM public.project_notification_center(500); PERFORM public.collect_notification_center_emails(100);
 SELECT id INTO STRICT dispatch FROM public.notification_center_email_dispatches WHERE recipient=u AND state='collecting';
 context:=public.notification_center_email_context_internal(dispatch,u); item:=context->'items'->0;
 PERFORM assert_eq(jsonb_array_length(context->'items'),1,'one payment received');
 PERFORM assert_eq(item->>'orderSymbol',(SELECT order_symbol FROM eshop.orders WHERE id=oid),'human order reference');
 PERFORM assert_eq(item#>>'{contact,email}','jana@example.test','authorized contact');
 PERFORM assert_eq(item#>>'{contact,name}','Jana','first name');
 PERFORM assert_eq(item#>>'{contact,surname}','Nováková','last name');
 PERFORM assert_eq((item#>>'{payment,remaining}')::numeric,80::numeric,'paid deposit still has full balance');
 PERFORM assert_eq(item->>'state','paid','deposit meets actual order eligibility');
 PERFORM assert_true(NOT EXISTS(SELECT 1 FROM public.notification_center_events WHERE organization=org AND data::text LIKE '%jana@example.test%'),'contact never stored in source events');
 fingerprint:=context->>'fingerprint';
 UPDATE eshop.orders SET data='{}' WHERE id=oid;
 context:=public.notification_center_email_context_internal(dispatch,u);
 PERFORM assert_true(context->>'fingerprint'<>fingerprint,'contact edits invalidate sealed content');
 PERFORM assert_eq(context#>'{items,0,contact}','{}'::jsonb,'missing contacts remain absent');
 INSERT INTO eshop.transactions(amount,currency,bank_account_id,date,transaction_type) VALUES(90,'CZK',bank,now(),'manual') RETURNING id INTO tx;
 PERFORM public.apply_transaction_pairing(tx,pi,'test','system');
 context:=public.notification_center_email_context_internal(dispatch,u);
 PERFORM assert_eq((context#>>'{items,0,payment,paid}')::numeric,110::numeric,'current cumulative money includes later top-up');
 PERFORM assert_eq((context#>>'{items,0,payment,overpaid}')::numeric,10::numeric,'overpayment explicit');
 PERFORM assert_eq((context#>>'{items,0,payment,remaining}')::numeric,0::numeric,'overpayment cannot show negative debt');
 fingerprint:=context->>'fingerprint';
 INSERT INTO eshop.transactions(amount,currency,bank_account_id,date,transaction_type,payment_info) VALUES(-30,'CZK',bank,now(),'return',pi);
 PERFORM public.refresh_payment_info_totals_internal(pi);
 context:=public.notification_center_email_context_internal(dispatch,u);
 PERFORM assert_eq((context#>>'{items,0,payment,paid}')::numeric,80::numeric,'refund reduces current net payment');
 PERFORM assert_eq((context#>>'{items,0,payment,remaining}')::numeric,20::numeric,'refund restores balance');
 PERFORM assert_true(context->>'fingerprint'<>fingerprint,'financial changes invalidate prepared content');
 UPDATE eshop.orders SET state='storno',data='{"name":"Jana"}' WHERE id=oid;
 context:=public.notification_center_email_context_internal(dispatch,u);
 PERFORM assert_eq(context#>>'{items,0,state}','storno','cancelled order is not reported as paid');
 UPDATE public.occasion_users SET is_editor_order_view=false WHERE occasion=oc AND "user"=u;
 context:=public.notification_center_email_context_internal(dispatch,u);
 PERFORM assert_eq(jsonb_array_length(context->'items'),0,'revoked order permission removes private data');
END $$;
ROLLBACK;
