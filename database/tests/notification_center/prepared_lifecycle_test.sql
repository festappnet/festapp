BEGIN;
DO $$
DECLARE org bigint;oc bigint;viewer uuid:=gen_random_uuid();other uuid:=gen_random_uuid();ev uuid;v jsonb;old jsonb;tok uuid;rev text;n integer;
BEGIN
 INSERT INTO public.organizations(title) VALUES('Prepared lifecycle') RETURNING id INTO org;
 INSERT INTO auth.users(id) VALUES(viewer),(other);
 INSERT INTO public.user_info(id,organization) VALUES(viewer,org),(other,org);
 INSERT INTO public.occasions(organization,title,link,start_time,end_time) VALUES(org,'Lifecycle',gen_random_uuid()::text,now(),now()+interval '1 day') RETURNING id INTO oc;
 INSERT INTO public.occasion_users(occasion,"user",is_editor_order_view) VALUES(oc,viewer,true),(oc,other,true);
 INSERT INTO public.notification_center_organizations(organization,initialized_at) VALUES(org,now()-interval '60 days');
 ev:=public.notification_center_publish_internal(org,oc,'order_created','lifecycle',jsonb_build_object('count',1,'formContext',jsonb_build_object('allowsMultiple',false)));
 PERFORM public.project_notification_center(500);
 PERFORM set_config('request.jwt.claim.sub',viewer::text,true);
 v:=public.get_notification_center_view(org,oc);
 FOR i IN 1..20 LOOP PERFORM public.prepare_notification_center(100);END LOOP;
 v:=public.get_notification_center_view(org,oc);tok:=(v->>'viewToken')::uuid;rev:=v->>'revision';
 PERFORM assert_eq(v->>'state','ready','prepared lifecycle ready');
 old:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>tok,p_revision=>rev);
 PERFORM assert_true((old->>'unchanged')::boolean,'unchanged refresh confirms live display inputs');
 UPDATE public.occasions SET title='Renamed occasion' WHERE id=oc;
 old:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>tok,p_revision=>rev);
 PERFORM assert_eq(old#>>'{items,0,occasionTitle}','Renamed occasion','display fingerprint detects live source edit');
 PERFORM set_config('request.jwt.claim.sub',other::text,true);
 old:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>tok);
 PERFORM assert_true(old->>'state' IN ('denied','expired'),'token cannot cross recipients');
 PERFORM set_config('request.jwt.claim.sub',viewer::text,true);
 FOR i IN 1..3 LOOP old:=public.get_notification_center_view(org,oc);END LOOP;
 old:=public.get_notification_center_view(org,oc);
 PERFORM assert_eq(old->>'state','view_limit','four live leases are enforced');
 old:=public.get_notification_center_view(org,oc,p_mode=>'close_all');
 PERFORM assert_eq((SELECT count(*) FROM public.notification_center_views WHERE organization=org AND recipient=viewer),0::bigint,'explicit close all releases only owned leases');
 v:=public.get_notification_center_view(org,oc);tok:=(v->>'viewToken')::uuid;
 UPDATE public.notification_center_views SET expires_at=clock_timestamp()-interval '1 second' WHERE token=tok;
 old:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>tok);
 PERFORM assert_eq(old->>'state','expired','expired lease never silently reopens');
 v:=public.get_notification_center_view(org,oc);tok:=(v->>'viewToken')::uuid;rev:=v->>'revision';
 UPDATE public.occasion_users SET is_editor_order_view=false WHERE occasion=oc AND "user"=viewer;
 old:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>tok,p_revision=>rev);
 PERFORM assert_false(coalesce((old->>'unchanged')::boolean,false),'revoked role cannot reuse unchanged private rows');
 PERFORM assert_true(NOT EXISTS(SELECT 1 FROM jsonb_array_elements(coalesce(old->'items','[]')) x WHERE x->>'state'='ready'),'revocation removes private data immediately');
 UPDATE public.occasion_users SET is_editor_order_view=true WHERE occasion=oc AND "user"=viewer;
 -- A physical expiry is an indexed off-path repair, not a hot-path scan.
 PERFORM public.notification_center_prepared_invalidate(ev);
 UPDATE public.notification_center_events SET occurred_at=clock_timestamp()-interval '31 days' WHERE id=ev;
 old:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>tok);
 PERFORM assert_eq(old->>'state','preparing','expiry/source debt is explicit');
 FOR i IN 1..20 LOOP PERFORM public.prepare_notification_center(100);PERFORM public.prepare_notification_center_views(100);END LOOP;
 old:=public.get_notification_center_view(org,oc,p_mode=>'refresh',p_view=>tok);
 PERFORM assert_true(NOT EXISTS(SELECT 1 FROM jsonb_array_elements(coalesce(old->'items','[]')) x WHERE x->>'state'='ready'),'expired activity removed from retained view');
 PERFORM public.prepare_notification_center_views(100);
 PERFORM assert_false(EXISTS(SELECT 1 FROM public.notification_center_views WHERE token=(v->>'viewToken')::uuid AND expires_at<=clock_timestamp()),'bounded worker reclaims expired leases');
END $$;
ROLLBACK;
