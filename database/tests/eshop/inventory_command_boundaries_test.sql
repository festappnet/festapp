DO $$
DECLARE actor uuid; org bigint; un bigint; oc bigint; pool bigint; resource bigint; bundle jsonb; result jsonb; cmd uuid:=gen_random_uuid();
BEGIN
 PERFORM public.create_user_for_test('inventory-boundary','inventory-boundary@example.invalid');actor:=public.get_user_id('inventory-boundary');
 INSERT INTO public.organizations(title) VALUES('Inventory boundary') RETURNING id INTO org;
 UPDATE public.user_info SET organization=org WHERE id=actor;
 INSERT INTO public.units(title,organization) VALUES('Inventory boundary',org) RETURNING id INTO un;
 INSERT INTO public.occasions(title,organization,unit,link,start_time,end_time,data) VALUES('Inventory boundary',org,un,gen_random_uuid()::text,now(),now()+interval '1 day','{"client_sync_v1":false}') RETURNING id INTO oc;
 INSERT INTO public.occasion_users(occasion,"user",is_editor_order,is_editor_order_view) VALUES(oc,actor,true,true);
 INSERT INTO public.inventory_pools(title,occasion) VALUES('Original',oc) RETURNING id INTO pool;
 INSERT INTO public.inventory_contexts(inventory_pool,title) VALUES(pool,'Retained context');
 PERFORM set_config('request.jwt.claim.sub',actor::text,true);PERFORM set_config('request.jwt.claim.role','authenticated',true);
 bundle:=jsonb_build_object('pool',jsonb_build_object('id',pool,'occasion',oc,'title','Legacy save'),'contexts','null'::jsonb);
 EXECUTE 'SET LOCAL ROLE authenticated';
 result:=public.update_inventory_pool_bundle(bundle);
 ASSERT result#>>'{pool,title}'='Legacy save';
 bundle:=jsonb_set(bundle,'{pool,title}','"Canonical save"');
 result:=public.save_inventory_pool_client_sync_v1(oc,cmd,1,bundle-'contexts');
 ASSERT result->>'code'='200';ASSERT public.save_inventory_pool_client_sync_v1(oc,cmd,1,bundle-'contexts')=result;
 ASSERT public.save_inventory_pool_client_sync_v1(oc,gen_random_uuid(),1,bundle)->>'status'='conflict';
 ASSERT jsonb_array_length(result#>'{data,bundle,contexts}')=1, 'omitted/null contexts preserve prior rows';
 ASSERT public.save_inventory_pool_client_sync_v1(oc,gen_random_uuid(),2,jsonb_set(bundle,'{contexts}','[]'))->>'code'='200';
 PERFORM public.update_resource(jsonb_build_object('inventory_pool',pool,'title','Empty resource','capacity',0,'booking_rules',NULL));
 EXECUTE 'RESET ROLE';
 SELECT id INTO resource FROM public.resources WHERE inventory_pool=pool;
 ASSERT resource IS NOT NULL;
 ASSERT (SELECT count(*)=1 FROM public.resources WHERE inventory_pool=pool), 'facade must not recurse or double-create';
 ASSERT public.get_inventory_pool_bundle(pool)->>'aggregate_version'='4';
 ASSERT (SELECT booking_rules='{}'::jsonb FROM public.resources WHERE id=resource);
 ASSERT NOT EXISTS(SELECT 1 FROM public.inventory_contexts WHERE inventory_pool=pool), 'explicit empty contexts clear rows';
 ASSERT NOT has_function_privilege('authenticated','public.update_inventory_pool_bundle_internal_v1(jsonb)','EXECUTE');
 ASSERT NOT has_function_privilege('authenticated','public.report_cleaning_issue_internal_v1(bigint,text,text)','EXECUTE');
 EXECUTE 'SET LOCAL ROLE authenticated';
 PERFORM public.delete_resource(resource);
 PERFORM public.delete_inventory_pool(pool);
 EXECUTE 'RESET ROLE';
 ASSERT NOT EXISTS(SELECT 1 FROM public.inventory_pools WHERE id=pool);
END $$;
