BEGIN;
DO $$
DECLARE actor uuid; oc bigint; bank bigint; f uuid; before_count bigint; result jsonb;
BEGIN
 PERFORM create_user_for_test('demo_reader','demo-reader@example.invalid');
 actor:=get_user_id('demo_reader');
 UPDATE public.user_info SET organization=1 WHERE id=actor;
 SELECT occasion,bank_account INTO STRICT oc,bank FROM public.demo_occasions WHERE organization=1 AND fixture_version='2026-10-14.3' AND demo_key='ball';
 UPDATE public.demo_occasions SET is_listed=true WHERE organization=1 AND fixture_version='2026-10-14.3';
 PERFORM set_config('request.jwt.claim.sub',actor::text,true);
 PERFORM set_config('request.jwt.claim.role','authenticated',true);
 result:=public.get_demo_occasions(1);
 PERFORM assert_eq(jsonb_array_length(result->'items'),3,'three tenant demos');
 PERFORM assert_false((result->>'hasOwnWork')::boolean,'reader without Unit has no own work');
 PERFORM assert_true(public.can_read_demo_occasion(oc),'read without membership');
 PERFORM assert_false(public.get_is_editor_on_occasion(oc),'no write role');
 PERFORM assert_true(public.get_is_editor_order_view_on_occasion(oc),'order read capability');
 BEGIN PERFORM public.check_occasion_writable(oc); RAISE EXCEPTION 'demo writable';
 EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 BEGIN PERFORM public.check_bank_account_writable(bank); RAISE EXCEPTION 'demo bank writable';
 EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 BEGIN PERFORM public.update_bank_account(bank,'123/0100','Changed'); RAISE EXCEPTION 'demo bank update accepted';
 EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 SELECT key INTO f FROM public.forms WHERE occasion=oc LIMIT 1;
 PERFORM assert_true((public.get_form(f)->'data'->>'demo_simulation')::boolean,'server marks demo form');
 PERFORM assert_true((public.get_form(f)->'data'->>'is_open')::boolean,'demo signup form is open');
 BEGIN PERFORM public.create_ticket_order_internal_v1(jsonb_build_object('form',f)); RAISE EXCEPTION 'demo checkout accepted';
 EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 BEGIN PERFORM public.select_spot(f,gen_random_uuid(),(SELECT id FROM eshop.spots WHERE occasion=oc LIMIT 1),true);
 RAISE EXCEPTION 'demo reservation accepted'; EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 SELECT count(*) INTO before_count FROM public.email_messages;
 BEGIN PERFORM public.enqueue_email('custom',jsonb_build_object('organization',1,'occasion',oc),'demo@example.invalid','{}','demo-test','custom');
 RAISE EXCEPTION 'demo email accepted'; EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 PERFORM assert_eq((SELECT count(*) FROM public.email_messages),before_count,'no email side effect');
 PERFORM assert_false(EXISTS(SELECT 1 FROM eshop.bank_sync_connections WHERE bank_account_id=bank),'no BankSync');
 PERFORM assert_true(EXISTS(SELECT 1 FROM eshop.transactions WHERE bank_account_id=bank AND payment_info IS NULL),'unmatched payment exists');
 UPDATE public.demo_occasions SET is_listed=false WHERE occasion=oc;
 PERFORM assert_false(public.can_read_demo_occasion(oc),'withdrawn version loses read');
 PERFORM assert_true(public.is_demo_occasion(oc),'withdrawn version remains protected');
 INSERT INTO public.organizations(title) VALUES('Foreign demo tenant');
 UPDATE public.user_info SET organization=(SELECT id FROM public.organizations WHERE id<>1 LIMIT 1) WHERE id=actor;
 PERFORM assert_false(public.can_read_demo_occasion(oc),'other tenant loses access');
 BEGIN PERFORM public.get_demo_occasions(1); RAISE EXCEPTION 'foreign catalog accepted';
 EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 PERFORM set_config('request.jwt.claim.sub','',true);
 PERFORM assert_false(public.can_read_demo_occasion(oc),'anonymous read denied');
 PERFORM assert_eq((public.get_form(f)->>'code')::int,404,'anonymous cannot obtain demo form');
 PERFORM public.check_occasion_writable(-1);
END $$;
ROLLBACK;
