-- Run as the real object owner after the default-ACL phase.
DO $$
DECLARE r text; p record;
BEGIN
 CREATE TABLE public.data_security_default_probe(id bigint GENERATED BY DEFAULT AS IDENTITY);
 CREATE FUNCTION public.data_security_default_probe() RETURNS boolean LANGUAGE sql AS 'select true';
 CREATE TABLE eshop.data_security_default_probe(id bigint);
 FOR r IN SELECT unnest(ARRAY['anon','authenticated']) LOOP
   IF has_table_privilege(r,'public.data_security_default_probe','SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
   OR has_table_privilege(r,'eshop.data_security_default_probe','SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
   OR has_sequence_privilege(r,'public.data_security_default_probe_id_seq','USAGE,SELECT,UPDATE')
   OR has_function_privilege(r,'public.data_security_default_probe()','EXECUTE') THEN RAISE EXCEPTION 'default ACL leaked: %',r; END IF;
   IF NOT has_function_privilege(r,'public.get_occasion_for_context_v1(bigint)','EXECUTE') THEN RAISE EXCEPTION 'explicit reader lost'; END IF;
   FOR p IN SELECT oid FROM pg_class WHERE relnamespace='storage'::regnamespace AND relname IN ('objects','buckets','buckets_analytics') LOOP
     IF has_table_privilege(r,p.oid,'TRUNCATE,REFERENCES,TRIGGER') THEN RAISE EXCEPTION 'storage DDL grant remains'; END IF;
   END LOOP;
 END LOOP;
END $$;
