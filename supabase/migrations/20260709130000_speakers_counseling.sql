-- Migration: Speakers & Counseling (speakers feature) — Phase 1 (SQL)
--
-- Adds the 4 new tables (speakers, speaker_topics, speaker_topic_links,
-- event_speakers) with RLS + SELECT-only policies + moddatetime triggers, and
-- all speaker/counseling RPCs, plus the modified sign_user_to_event (counseling
-- branch) and the relocated search_occasion_content (excludes counseling slots).
--
-- Idempotent: CREATE TABLE IF NOT EXISTS, DROP POLICY/TRIGGER IF EXISTS,
-- CREATE OR REPLACE FUNCTION throughout.
--
-- !!! DO NOT APPLY TO LIVE YET. The Flutter client and admin/user UI that drive
-- these RPCs are not implemented; this migration is committed alongside Phase 1
-- and deployed only once the full feature is ready (see plan section 8).
-- =============================================================================

-- ---------------------------------------------------------------------------
-- (1) Tables + indexes (authoritative DDL: database/tables/tables.sql §12)
-- ---------------------------------------------------------------------------

create table if not exists public.speakers (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  occasion    BIGINT NOT NULL,
  title       TEXT NOT NULL,
  subtitle    TEXT NULL,
  description TEXT NULL,
  image       TEXT NULL,
  "order"     BIGINT NOT NULL DEFAULT 0,
  is_hidden   BOOLEAN NOT NULL DEFAULT false,
  data        JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT speakers_pkey PRIMARY KEY (id),
  CONSTRAINT speakers_occasion_fkey FOREIGN KEY (occasion) REFERENCES public.occasions (id) ON DELETE CASCADE,
  CONSTRAINT speakers_title_length_check CHECK (char_length(title) <= 200)
) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS speakers_occasion_idx ON public.speakers (occasion);

create table if not exists public.speaker_topics (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  occasion    BIGINT NOT NULL,
  code        TEXT NULL,
  title       TEXT NOT NULL,
  "order"     BIGINT NOT NULL DEFAULT 0,
  is_hidden   BOOLEAN NOT NULL DEFAULT false,
  CONSTRAINT speaker_topics_pkey PRIMARY KEY (id),
  CONSTRAINT speaker_topics_occasion_fkey FOREIGN KEY (occasion) REFERENCES public.occasions (id) ON DELETE CASCADE
) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS speaker_topics_occasion_idx ON public.speaker_topics (occasion);
CREATE UNIQUE INDEX IF NOT EXISTS speaker_topics_occasion_code_uidx
  ON public.speaker_topics (occasion, code) WHERE (code IS NOT NULL);

create table if not exists public.speaker_topic_links (
  speaker BIGINT NOT NULL,
  topic   BIGINT NOT NULL,
  CONSTRAINT speaker_topic_links_pkey PRIMARY KEY (speaker, topic),
  CONSTRAINT speaker_topic_links_speaker_fkey FOREIGN KEY (speaker) REFERENCES public.speakers (id) ON DELETE CASCADE,
  CONSTRAINT speaker_topic_links_topic_fkey FOREIGN KEY (topic) REFERENCES public.speaker_topics (id) ON DELETE CASCADE
) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS speaker_topic_links_topic_idx ON public.speaker_topic_links (topic);

create table if not exists public.event_speakers (
  event   BIGINT NOT NULL,
  speaker BIGINT NOT NULL,
  CONSTRAINT event_speakers_pkey PRIMARY KEY (event, speaker),
  CONSTRAINT event_speakers_event_fkey FOREIGN KEY (event) REFERENCES public.events (id) ON DELETE CASCADE,
  CONSTRAINT event_speakers_speaker_fkey FOREIGN KEY (speaker) REFERENCES public.speakers (id) ON DELETE CASCADE
) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS event_speakers_speaker_idx ON public.event_speakers (speaker);

-- ---------------------------------------------------------------------------
