const _DEFAULT_EMAIL = Deno.env.get("DEFAULT_EMAIL") || "";
export type EmailContext = {
  organization: number;
  occasion?: number | null;
  unit?: number | null;
  [key: string]: unknown;
};

export type EmailAttachment = {
  filename: string;
  content: unknown;
  contentType: string;
  encoding: string;
  disposition?: "ATTACHMENT" | "INLINE";
  contentId?: string;
};

export type EmailTemplate = {
  id: string | number | null;
  code?: string | null;
  subject: string;
  html: string;
};

type EmailWrapper = {
  html?: string | null;
};

type ResolvedEmail = {
  template?: EmailTemplate | null;
  wrapper?: EmailWrapper | null;
};

export type DeliverEmailInput = {
  to: string;
  /** Auth/user_info recipient when the message concerns one concrete account. */
  recipientUser?: string;
  templateCode?: string;
  context: EmailContext;
  substitutions: Record<string, unknown>;
  subjectSubstitutions?: Record<string, unknown>;
  /** Trusted ticket block, composed once before the inherited wrapper. */
  ticketBlock?: string;
  /** PNG from an eligible bank payment, generated by the order email producer. */
  paymentQr?: { png: Uint8Array; lang: unknown; inline: boolean };
  /** Candidate actions for authored slots; never appended to a custom body. */
  requiredLinks?: EmailRequiredLink[];
  attachments?: EmailAttachment[];
  from?: string;
  replyTo?: string;
  /** Stable RFC Message-ID used by durable workers across delivery retries. */
  messageId?: string;
  /**
   * Preserves editor-provided template snapshots while the wrapper is still
   * resolved centrally from templateCode and context.
   */
  template?: EmailTemplate;
};

export type EmailDeliveryResult = {
  templateId: string | number | null;
  logged: boolean;
};

export class EmailTemplateNotFoundError extends Error {
  constructor(templateCode: string) {
    super(`Template not found for code ${templateCode}`);
    this.name = "EmailTemplateNotFoundError";
  }
}

export type PreparedEmail = {
  from: string;
  to: string;
  subject: string;
  html: string;
  replyTo: string;
  attachments: Array<
    {
      filename: string;
      content: string;
      contentType: string;
      encoding: "base64";
      disposition?: "ATTACHMENT" | "INLINE";
      contentId?: string;
    }
  >;
};
export function encodeAttachment(content: unknown, encoding: string): string {
  if (encoding === "base64" && typeof content === "string") return content;
  const bytes = content instanceof Uint8Array
    ? content
    : typeof content === "string"
    ? new TextEncoder().encode(content)
    : null;
  if (!bytes) throw new Error("invalid_email_attachment");
  let binary = "";
  for (let offset = 0; offset < bytes.length; offset += 8192) {
    binary += String.fromCharCode(...bytes.subarray(offset, offset + 8192));
  }
  return btoa(binary);
}
export async function renderEmail(
  input: DeliverEmailInput,
  resolver?: (code: string, context: EmailContext) => Promise<ResolvedEmail>,
): Promise<PreparedEmail> {
  if (!resolver) {
    const { getEmailTemplateAndWrapper } = await import("./supabaseUtil.ts");
    resolver = getEmailTemplateAndWrapper;
  }
  const resolved = await resolver(input.templateCode ?? "", input.context);
  const template = input.template ?? resolved?.template;
  if (
    !template || typeof template.subject !== "string" ||
    typeof template.html !== "string"
  ) throw new EmailTemplateNotFoundError(input.templateCode ?? "inline");
  assertCanonicalEmailTemplate(template.subject);
  assertCanonicalEmailTemplate(template.html);
  assertCanonicalEmailTemplate(resolved?.wrapper?.html);
  const subject = substituteEmailSubject(
    template.subject,
    input.subjectSubstitutions ?? input.substitutions,
  );
  let body = template.html;
  const ticketBlock = input.ticketBlock ??
    (input.templateCode === "TICKET_ORDER_PAYMENT_DONE" ? "" : undefined);
  if (ticketBlock !== undefined) {
    const marker = "{{tickets}}", first = body.indexOf(marker);
    body = first < 0 ? body + ticketBlock : body.slice(0, first) + ticketBlock +
      body.slice(first + marker.length).replaceAll(marker, "");
  }
  const paymentAction = String(input.substitutions.paymentAction ?? "");
  const paymentValues: Record<string, unknown> = {
    ...input.substitutions,
    paymentAction: "<!--festapp-payment-action-->",
  };
  if (
    paymentAction &&
    (body.includes("{{paymentAction}}") ||
      resolved?.wrapper?.html?.includes("{{paymentAction}}"))
  ) {
    for (const key of ["balanceReasoning", "paymentDetails"]) {
      if (typeof paymentValues[key] === "string") {
        paymentValues[key] = paymentValues[key].replaceAll(paymentAction, "");
      }
    }
  }
  const substitutedBody = substituteEmailHtml(body, paymentValues);
  const composeHtml = (paymentQr?: EmailPaymentQrBlock) =>
    styleEmailPlainValues(completeEmailContent(
      substitutedBody,
      input.requiredLinks ?? [],
      resolved?.wrapper?.html,
      paymentAction,
      paymentQr,
    ));
  const prepared: PreparedEmail = {
    from: input.from ?? _DEFAULT_EMAIL,
    to: input.to,
    subject,
    html: "",
    replyTo: input.replyTo ?? _DEFAULT_EMAIL,
    attachments: (input.attachments ?? []).map((a) => ({
      filename: a.filename,
      content: encodeAttachment(a.content, a.encoding),
      contentType: a.contentType,
      encoding: "base64",
      ...(a.disposition ? { disposition: a.disposition } : {}),
      ...(a.contentId ? { contentId: a.contentId } : {}),
    })),
  };
  if (input.paymentQr) {
    const cs = resolveEmailLanguage(input.paymentQr.lang) === "cs";
    const download = {
      filename: cs ? "qr-platba.png" : "qr-payment.png",
      content: encodeAttachment(input.paymentQr.png, "binary"),
      contentType: "image/png",
      encoding: "base64",
      disposition: "ATTACHMENT",
    } as const;
    prepared.attachments.push(download);
    if (!input.paymentQr.inline) {
      prepared.html = composeHtml();
      return prepared;
    }

    const contentId = `festapp-payment-${crypto.randomUUID()}@festapp.net`;
    const alt = cs
      ? "QR kód pro platbu bankovním převodem"
      : "Bank transfer QR code";
    const title = cs ? "Zaplaťte pomocí QR kódu" : "Pay with the QR code";
    const scanInstructions = cs
      ? "Naskenujte ho v aplikaci mobilního bankovnictví."
      : "Scan it in your mobile banking app.";
    const hint = cs
      ? "QR kód si můžete stáhnout z přílohy."
      : "You can download the QR code from the attachment.";
    return {
      ...prepared,
      html: composeHtml({
        html:
          `<div style="margin:16px 0"><p style="margin:0 0 4px;font-size:18px;font-weight:bold">${title}</p><p style="margin:0 0 8px">${scanInstructions}</p><img src="cid:${contentId}" alt="${alt}" width="240" height="240" style="display:block;width:240px;max-width:100%;height:auto;background:#ffffff"><p style="margin:8px 0 0">${hint}</p></div>`,
        paymentDetails: ["paymentDetails", "balanceReasoning"].map((key) =>
          String(paymentValues[key] ?? "")
        ),
      }),
      attachments: [...prepared.attachments, {
        ...download,
        filename: "qr-inline.png",
        disposition: "INLINE",
        contentId,
      }],
    };
  }
  prepared.html = composeHtml();
  return prepared;
}
