"""Emit browser SVG and Flutter paths from the same canonical logo and timeline."""
import copy
import json
import xml.etree.ElementTree as ET
from fontTools.svgLib.path import SVGPath
from fontTools.pens.basePen import BasePen

NS = '{http://www.w3.org/2000/svg}'
ET.register_namespace('', NS[1:-1])

def number(value):
    return f'{value:.6f}'.rstrip('0').rstrip('.') or '0'

class DartPathPen(BasePen):
    def __init__(self):
        super().__init__(None)
        self.commands = []
    def command(self, name, *points):
        values = ', '.join(number(v) for p in points for v in p)
        self.commands.append(f'..{name}({values})')
    def _moveTo(self, p): self.command('moveTo', p)
    def _lineTo(self, p): self.command('lineTo', p)
    def _curveToOne(self, a, b, c): self.command('cubicTo', a, b, c)
    def _qCurveToOne(self, a, b): self.command('quadraticBezierTo', a, b)
    def _closePath(self): self.commands.append('..close()')
    def _endPath(self): pass

def emit_outline_assets(root):
    timeline = json.loads((root / 'source/loading-timeline.json').read_text())
    duration = timeline['durationMs']
    parts = timeline['parts']
    pulse = timeline['pulse']
    for dark in (False, True):
        suffix = '-dark' if dark else ''
        svg = ET.parse(root / f'vstupenky-online-transparent{suffix}.svg').getroot()
        groups = {e.get('id'): e for e in svg if e.tag == NS + 'g'}
        out = ET.Element(NS+'svg', {
            'viewBox': ' '.join(map(str,timeline['viewBox'])), 'width':'360','height':'285',
            'class':'vstupenky-loading', 'role':'img', 'aria-label':'vstupenky.online',
        })
        ET.SubElement(out, NS+'title').text = 'vstupenky.online - načítání'
        css = ['.vstupenky-loading .outline{fill:none;stroke-width:1.25;stroke-linecap:round;stroke-linejoin:round}',
               '.vstupenky-loading .outline path{fill:none;stroke-dasharray:1;stroke-dashoffset:1}']
        for name, times in parts.items():
            for kind in ('fill','outline'):
                frames = ''.join(f'{number(t*100)}%{{opacity:{number(v)}}}' for t,v in times[kind])
                css.append(f'@keyframes vstupenky-{kind}-{name}{{{frames}}}')
                css.append(f'.vstupenky-loading .{kind}-{name}{{animation:vstupenky-{kind}-{name} {duration}ms linear forwards}}')
            a,b = times['draw']
            css.append(f'@keyframes vstupenky-draw-{name}{{0%,{number(a*100)}%{{stroke-dashoffset:1}}{number(b*100)}%,100%{{stroke-dashoffset:0}}}}')
            css.append(f'.vstupenky-loading .outline-{name} path{{animation:vstupenky-draw-{name} {duration}ms linear forwards}}')
        css += [
            '.vstupenky-loading .filled>g{opacity:1}.vstupenky-loading .outline>g{opacity:0}',
            '@keyframes vstupenky-pulse{0%,100%{opacity:1}50%{opacity:' + number(pulse['minOpacity']) + '}}',
            f'.vstupenky-loading .pulse{{animation:vstupenky-pulse {pulse["durationMs"]}ms ease-in-out {duration}ms infinite}}',
        ]
        css.append('@media(prefers-reduced-motion:reduce){.vstupenky-loading .pulse{animation:none;opacity:1}}')
        css.append('@media(prefers-reduced-motion:reduce){.vstupenky-loading .filled>g{animation:none;opacity:1}.vstupenky-loading .outline{display:none}}')
        ET.SubElement(out, NS+'style').text = '\n'.join(css)
        pulse_layer = ET.SubElement(out, NS+'g', {'class': 'pulse'})
        for kind in ('fill','outline'):
            layer = ET.SubElement(pulse_layer,NS+'g',{'class':'filled' if kind=='fill' else 'outline'})
            for name in parts:
                g = copy.deepcopy(groups[name]); color = g.attrib.pop('fill')
                g.attrib.pop('id'); g.set('class',kind+'-'+name)
                if kind=='outline':
                    g.set('stroke',color)
                    for path in g.iter(NS+'path'):
                        path.set('pathLength','1'); path.set('vector-effect','non-scaling-stroke')
                else: g.set('fill',color)
                layer.append(g)
        (root/f'vstupenky-online-loading{suffix}.svg').write_text(ET.tostring(out,encoding='unicode')+'\n')
    # Flatten every SVG transform before emitting Flutter commands. No separate
    # drawing, font substitution, raster, or hand-maintained Flutter logo exists.
    normal = ET.parse(root/'vstupenky-online-transparent.svg').getroot()
    dart = ["// Generated by assets/brand/vstupenky-online/tools/build_vectors.py.",
            "// Canonical unioned SVG geometry and source/loading-timeline.json.",
            "part of 'brand_loading_indicator.dart';", '',
            f'const _brandCycle = Duration(milliseconds: {duration});',
            f'const _brandPulseCycle = Duration(milliseconds: {pulse["durationMs"]});',
            f'const _brandPulseMinOpacity = {number(pulse["minOpacity"])};',
            'const _brandViewBox = Rect.fromLTWH('+', '.join(map(str,timeline['viewBox']))+');',
            'final _brandLogoParts = <_LogoPart>[']
    for name, times in parts.items():
        group = next(e for e in normal if e.get('id')==name)
        wrapper=ET.Element(NS+'svg');wrapper.append(copy.deepcopy(group))
        for node in wrapper.iter():
            if node.get('transform') == 'translate(1024 0) scale(-1 1)':
                node.set('transform', 'matrix(-1 0 0 1 1024 0)')

        path_commands=[]
        for node in wrapper.iter(NS+'path'):
            single=ET.Element(NS+'svg');single.append(copy.deepcopy(node))
            pen=DartPathPen();SVGPath.fromstring(ET.tostring(single)).draw(pen)
            path_commands.append('(Path()'+''.join(pen.commands)+')')
        points=lambda pairs:'const ['+', '.join('Offset('+number(t)+', '+number(v)+')' for t,v in pairs)+']'
        dart += ['  _LogoPart(', '    paths: ['+', '.join(path_commands)+'],',
                 f"    blue: {'true' if name in ('center','domain') else 'false'},",
                 f"    drawStart: {number(times['draw'][0])}, drawEnd: {number(times['draw'][1])},",
                 '    fill: '+points(times['fill'])+',', '    outline: '+points(times['outline'])+',', '  ),']
    dart.append('];\n')
    (root.parents[2]/'lib/widgets/brand_loading_paths.dart').write_text('\n'.join(dart))
